    GAS_TOTAL(:,ID),GAS_RATE(:,ID),HEAT_TOTAL(ID),HEAT_RATE(ID)
ENDDO
END SUBROUTINE
SUBROUTINE CONFIG_IO(LU,READ_MODE)
INTEGER,INTENT(IN) :: LU
LOGICAL,INTENT(IN) :: READ_MODE
INTEGER :: M,J,NR,NRES,IOS
INTEGER,ALLOCATABLE :: RI(:)
REAL(EB),ALLOCATABLE :: RN(:)
REAL(EB) :: RHO0,CS(0:I_MAX_TEMP),KS(0:I_MAX_TEMP),HR(0:I_MAX_TEMP),NU(N_TRACKED_SPECIES),RATE
CHARACTER(LABEL_LENGTH) :: ID,MAT_IDS(N_MATL),SPEC_IDS(N_TRACKED_SPECIES)
TYPE(MATERIAL_TYPE),POINTER :: ML
IF (READ_MODE) THEN
 READ(LU,IOSTAT=IOS) MAT_IDS,SPEC_IDS
 CALL CHECK(IOS==0,'configuration identity record unreadable')
 CALL CHECK(ALL(MAT_IDS==MATERIAL%ID).AND.ALL(SPEC_IDS==SPECIES_MIXTURE%ID),'material/species ordering changed')
ELSE
 WRITE(LU) MATERIAL%ID,SPECIES_MIXTURE%ID
ENDIF
DO M=1,N_MATL
 ML=>MATERIAL(M)
 IF (READ_MODE) THEN
  READ(LU,IOSTAT=IOS) ID,RHO0,CS,KS,NR
  CALL CHECK(IOS==0,'material configuration record unreadable')
  CALL CHECK(ID==ML%ID.AND.RHO0==ML%RHO_S.AND.ALL(CS==ML%C_S).AND.ALL(KS==ML%K_S).AND.NR==ML%N_REACTIONS, &
    'restart material properties changed')
 ELSE
  WRITE(LU) ML%ID,ML%RHO_S,ML%C_S,ML%K_S,ML%N_REACTIONS
 ENDIF
 DO J=1,ML%N_REACTIONS
  IF (READ_MODE) THEN
   READ(LU,IOSTAT=IOS) HR,NU,NRES,RATE
   CALL CHECK(IOS==0,'reaction configuration record unreadable')
   CALL CHECK(ALL(HR==ML%H_R(J,:)).AND.ALL(NU==ML%NU_GAS(:,J)).AND.NRES==ML%N_RESIDUE(J).AND. &
     RATE==ML%MAX_REACTION_RATE(J),'restart reaction heat, yield or cap changed')
   ALLOCATE(RI(NRES),RN(NRES))
   READ(LU,IOSTAT=IOS) RI,RN
   CALL CHECK(IOS==0,'residue configuration record unreadable')
   CALL CHECK(ALL(RI==ML%RESIDUE_MATL_INDEX(1:NRES,J)).AND.ALL(RN==ML%NU_RESIDUE(1:NRES,J)), &
     'restart residue mapping changed')
   DEALLOCATE(RI,RN)
  ELSE
   WRITE(LU) ML%H_R(J,:),ML%NU_GAS(:,J),ML%N_RESIDUE(J),ML%MAX_REACTION_RATE(J)
   WRITE(LU) ML%RESIDUE_MATL_INDEX(1:ML%N_RESIDUE(J),J),ML%NU_RESIDUE(1:ML%N_RESIDUE(J),J)
  ENDIF
 ENDDO
ENDDO
END SUBROUTINE
SUBROUTINE E3_READ(LU,NM)
INTEGER,INTENT(IN) :: LU,NM
INTEGER :: N,NMATS,NN,NTOT,NG,IOS,J,ID,EXPECT_ID
REAL(EB) :: ST,V,REF(N_MATL),FRESH_REF(N_MATL)
CHARACTER(8) :: TAG
IF (.NOT.E3_READY) RETURN
READ(LU,IOSTAT=IOS) TAG,N,NMATS,NN,NTOT,NG,ST
CALL CHECK(IOS==0,'coupled checkpoint footer missing or unreadable')
CALL CHECK(TAG=='E3VOL003'.AND.NMATS==N_MATL.AND.NN==NB.AND.NTOT==NC.AND.NG==N_TRACKED_SPECIES, 'coupled checkpoint version/dimensions mismatch')
CALL CHECK(N==COUNT(VOLUME>0._EB.AND.OWNER==NM),'coupled checkpoint cell ownership mismatch')
CALL CONFIG_IO(LU,.TRUE.)
CALL CHECK(ABS(ST-MESHES(NM)%BC_CLOCK)<1.E-10_EB,'physical checkpoint clock differs from native wall clock')
READ_MIN=MIN(READ_MIN,ST); READ_MAX=MAX(READ_MAX,ST)
DO EXPECT_ID=OFFSET(NM)+1,OFFSET(NM)+MESHES(NM)%IBAR*MESHES(NM)%JBAR*MESHES(NM)%KBAR
 IF (VOLUME(EXPECT_ID)<=0._EB) CYCLE
 FRESH_REF=REFERENCE(:,EXPECT_ID)
 READ(LU,IOSTAT=IOS) ID,V,TEMPERATURE(EXPECT_ID),DENS(:,EXPECT_ID),MAT_RATE(:,EXPECT_ID),BINS(:,:,EXPECT_ID),REF,CONSUMED(:,EXPECT_ID), &
   GAS_TOTAL(:,EXPECT_ID),GAS_RATE(:,EXPECT_ID),HEAT_TOTAL(EXPECT_ID),HEAT_RATE(EXPECT_ID)
 CALL CHECK(IOS==0,'coupled physical cell record unreadable')
 CALL CHECK(ID==EXPECT_ID.AND.ABS(V-VOLUME(EXPECT_ID))<1.E-15_EB,'coupled checkpoint geometry mismatch')
 CALL CHECK(MAXVAL(ABS(REF-FRESH_REF))<1.E-12_EB,'coupled checkpoint initial material inventory mismatch')
 CALL CHECK(ALL(IEEE_IS_FINITE(DENS(:,EXPECT_ID))).AND.ALL(DENS(:,EXPECT_ID)>=0._EB), 'invalid restored densities')
 CALL CHECK(ALL(IEEE_IS_FINITE(BINS(:,:,EXPECT_ID))).AND.ALL(BINS(:,:,EXPECT_ID)>=0._EB), 'invalid restored bins')
 REFERENCE(:,EXPECT_ID)=REF
ENDDO
E3_TIME=ST
END SUBROUTINE
SUBROUTINE E3_RESTORE(T)
REAL(EB),INTENT(IN) :: T
INTEGER :: IE
IF (.NOT.E3_READY) RETURN
IF (RESTART.AND.N_MPI_PROCESSES>1) THEN
 CALL MPI_ALLREDUCE(MPI_IN_PLACE,READ_MIN,1,MPI_DOUBLE_PRECISION,MPI_MIN,MPI_COMM_WORLD,IE)
 CALL MPI_ALLREDUCE(MPI_IN_PLACE,READ_MAX,1,MPI_DOUBLE_PRECISION,MPI_MAX,MPI_COMM_WORLD,IE)
ENDIF
IF (RESTART) CALL CHECK(ABS(READ_MAX-READ_MIN)<1.E-10_EB,'mesh checkpoints contain different physical times')
CALL CHECK(E3_TIME<=T+1.E-10_EB.AND.ABS(E3_TIME-MESHES(LOWER_MESH_INDEX)%BC_CLOCK)<1.E-10_EB, &
           'coupled checkpoint wall-clock mismatch')
CALL SYNC_STATE; CALL E3_PROJECT
END SUBROUTINE
SUBROUTINE E3_OPEN(T)
REAL(EB),INTENT(IN) :: T
LOGICAL :: EXISTS
IF (.NOT.E3_READY.OR.MY_RANK/=0) RETURN
INQUIRE(FILE=TRIM(CHID)//'_e3_global.csv',EXIST=EXISTS)
IF (RESTART.AND.EXISTS) THEN
 OPEN(NEWUNIT=LU_LOG,FILE=TRIM(CHID)//'_e3_global.csv',POSITION='APPEND',STATUS='OLD')
ELSE
 OPEN(NEWUNIT=LU_LOG,FILE=TRIM(CHID)//'_e3_global.csv',STATUS='REPLACE')
 WRITE(LU_LOG,'(A)') 'Time,Initial_kg,Solid_kg,Reactive_kg,Gas_ledger_kg,Consumed_kg,Reaction_heat_J,Tmin_K,Tmax_K'
 CALL E3_REPORT(T)
ENDIF
END SUBROUTINE
SUBROUTINE E3_REPORT(T)
REAL(EB),INTENT(IN) :: T
INTEGER :: LU,ID,M,B
REAL(EB) :: SOLID,REACT,GAS,HEAT,TMIN,TMAX
IF (.NOT.E3_READY.OR.MY_RANK/=0) RETURN
SOLID=0; REACT=SUM(BINS); GAS=SUM(GAS_TOTAL); HEAT=SUM(HEAT_TOTAL)
TMIN=HUGE(1._EB); TMAX=0
DO ID=1,NC
 IF (VOLUME(ID)<=0._EB) CYCLE
 SOLID=SOLID+SUM(DENS(:,ID))*VOLUME(ID); TMIN=MIN(TMIN,TEMPERATURE(ID)); TMAX=MAX(TMAX,TEMPERATURE(ID))
ENDDO
WRITE(LU_LOG,'(9(ES25.16,:,","))') T,INITIAL_MASS,SOLID,REACT,GAS,SUM(CONSUMED),HEAT,TMIN,TMAX
FLUSH(LU_LOG)
CALL CHECK(ABS(SOLID+GAS-INITIAL_MASS)<MAX(1.E-12_EB,1.E-10_EB*INITIAL_MASS),'physical solid-to-gas mass ledger does not close')
IF (T<T_END-1.E-10_EB.AND.STOP_STATUS==0) RETURN
OPEN(NEWUNIT=LU,FILE=TRIM(CHID)//'_e3_cells.csv',STATUS='REPLACE')
WRITE(LU,'(A)') 'cell,mesh,i,j,k,volume_m3,T_K,material,rho_kgm3,reference_kg,consumed_kg'
DO ID=1,NC
 IF (VOLUME(ID)<=0._EB) CYCLE
 DO M=1,N_MATL
  WRITE(LU,'(5(I0,","),2(ES25.16,","),I0,3(",",ES25.16))') ID,OWNER(ID),GI(ID),GJ(ID),GK(ID), &
      VOLUME(ID),TEMPERATURE(ID),M,DENS(M,ID),REFERENCE(M,ID),CONSUMED(M,ID)
 ENDDO
ENDDO
CLOSE(LU)
OPEN(NEWUNIT=LU,FILE=TRIM(CHID)//'_e3_bins.csv',STATUS='REPLACE')
WRITE(LU,'(A)') 'cell,material,bin,energy_Jmol,weight,mass_kg,reference_kg'
DO ID=1,NC
 IF (VOLUME(ID)<=0._EB) CYCLE
 DO M=1,N_MATL
  IF (.NOT.MATERIAL(M)%EAE%ENABLED) CYCLE
  DO B=1,MATERIAL(M)%EAE%NN
   WRITE(LU,'(3(I0,","),4(ES25.16,:,","))') ID,M,B,MATERIAL(M)%EAE%ENERGY(B),MATERIAL(M)%EAE%WEIGHT(B),BINS(B,M,ID),REFERENCE(M,ID)
  ENDDO
 ENDDO
ENDDO
CLOSE(LU)
END SUBROUTINE
