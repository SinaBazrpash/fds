IMPLICIT NONE
PRIVATE
PUBLIC :: E3_READY,E3_SETUP,E3_ADVANCE,E3_PROJECT,E3_HEAT,E3_FLUX,E3_CAPTURE, &
          E3_DUMP,E3_READ,E3_RESTORE,E3_REPORT,E3_OPEN
LOGICAL :: E3_READY=.FALSE.
INTEGER :: NC=0,NB=0,LU_LOG=-1
INTEGER, ALLOCATABLE :: OFFSET(:),OWNER(:),GI(:),GJ(:),GK(:)
REAL(EB) :: E3_TIME=0._EB,INITIAL_MASS=0._EB,READ_MIN=HUGE(1._EB),READ_MAX=-HUGE(1._EB)
REAL(EB), ALLOCATABLE :: VOLUME(:),TEMPERATURE(:),DENS(:,:),BINS(:,:,:),REFERENCE(:,:), &
                        CONSUMED(:,:),MAT_RATE(:,:),GAS_TOTAL(:,:),GAS_RATE(:,:),HEAT_TOTAL(:),HEAT_RATE(:),CAP(:,:)
CONTAINS
SUBROUTINE CHECK(OK,MESSAGE)
LOGICAL,INTENT(IN) :: OK
CHARACTER(*),INTENT(IN) :: MESSAGE
INTEGER :: IE
IF (OK) RETURN
CALL SHUTDOWN('EAE3D experimental: '//MESSAGE,PROCESS_0_ONLY=.FALSE.)
IF (N_MPI_PROCESSES>1) CALL MPI_ABORT(MPI_COMM_WORLD,1,IE)
ERROR STOP 1
END SUBROUTINE
INTEGER FUNCTION CELL_ID(NM,I,J,K) RESULT(ID)
INTEGER,INTENT(IN) :: NM,I,J,K
CALL CHECK(NM>=1.AND.NM<=NMESHES,'invalid cell owner')
CALL CHECK(I>=1.AND.I<=MESHES(NM)%IBAR.AND.J>=1.AND.J<=MESHES(NM)%JBAR.AND. &
           K>=1.AND.K<=MESHES(NM)%KBAR,'node lies outside owner mesh')
ID=OFFSET(NM)+(K-1)*MESHES(NM)%IBAR*MESHES(NM)%JBAR+(J-1)*MESHES(NM)%IBAR+I
END FUNCTION
SUBROUTINE NODE_BOX(BC,OD,I,BOX)
TYPE(BOUNDARY_COORD_TYPE),INTENT(IN) :: BC
TYPE(BOUNDARY_ONE_D_TYPE),INTENT(IN) :: OD
INTEGER,INTENT(IN) :: I
REAL(EB),INTENT(OUT) :: BOX(6)
BOX=[BC%X1,BC%X2,BC%Y1,BC%Y2,BC%Z1,BC%Z2]
SELECT CASE(BC%IOR)
CASE(1); BOX(1)=BC%X1-OD%X(I); BOX(2)=BC%X1-OD%X(I-1)
CASE(-1); BOX(1)=BC%X1+OD%X(I-1); BOX(2)=BC%X1+OD%X(I)
CASE(2); BOX(3)=BC%Y1-OD%X(I); BOX(4)=BC%Y1-OD%X(I-1)
CASE(-2); BOX(3)=BC%Y1+OD%X(I-1); BOX(4)=BC%Y1+OD%X(I)
CASE(3); BOX(5)=BC%Z1-OD%X(I); BOX(6)=BC%Z1-OD%X(I-1)
CASE(-3); BOX(5)=BC%Z1+OD%X(I-1); BOX(6)=BC%Z1+OD%X(I)
END SELECT
END SUBROUTINE
REAL(EB) FUNCTION FRONT_FRACTION(OD,I) RESULT(F)
TYPE(BOUNDARY_ONE_D_TYPE),INTENT(IN) :: OD
INTEGER,INTENT(IN) :: I
REAL(EB) :: MID
! The supported path requires the native midpoint routing, without linings.
MID=0.5_EB*OD%X(SUM(OD%N_LAYER_CELLS(1:OD%N_LAYERS)))
F=MAX(0._EB,MIN(1._EB,(MID-OD%X(I-1))/(OD%X(I)-OD%X(I-1))))
END FUNCTION
SUBROUTINE SUM_REAL(A)
REAL(EB),CONTIGUOUS,INTENT(INOUT) :: A(:)
INTEGER :: IE
IF (N_MPI_PROCESSES>1) CALL MPI_ALLREDUCE(MPI_IN_PLACE,A,SIZE(A),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
END SUBROUTINE
SUBROUTINE E3_SETUP
INTEGER :: NM,IW,I,N,M,ID,II,JJ,KK,NOM,NN,IE,NS
REAL(EB) :: BOX(6),EXPECTED(6),VOL,RHO0(N_MATL),YC,THICK
REAL(EB),ALLOCATABLE :: COVER(:,:),ROUTE(:),TEMP_WEIGHT(:),COUNTS(:),CELL_BOXES(:,:)
TYPE(MESH_TYPE),POINTER :: G
TYPE(WALL_TYPE),POINTER :: WC
TYPE(SURFACE_TYPE),POINTER :: SF
TYPE(BOUNDARY_COORD_TYPE),POINTER :: BC
TYPE(BOUNDARY_ONE_D_TYPE),POINTER :: OD
TYPE(INTERNAL_NODE_TYPE),POINTER :: NODE
TYPE(MATERIAL_TYPE),POINTER :: ML
IF (.NOT.EAE_ACTIVE) RETURN
IF (.NOT.ANY(SURFACE%EAE_HT3D)) RETURN
CALL CHECK(.NOT.CC_IBM.AND.TIME_SHRINK_FACTOR==1._EB,'requires Cartesian meshes and unscaled physical time')
CALL CHECK(.NOT.TWO_D,'requires three-dimensional meshes')
ALLOCATE(OFFSET(NMESHES))
NC=0
DO NM=1,NMESHES
 OFFSET(NM)=NC; NC=NC+MESHES(NM)%IBAR*MESHES(NM)%JBAR*MESHES(NM)%KBAR
ENDDO
NB=MAXVAL(MATERIAL%EAE%NN)
CALL CHECK(REAL(NC,EB)*N_MATL*NB<=2.E7_EB,'experimental replicated mirror allocation exceeds 20 million bins')
ALLOCATE(OWNER(NC),GI(NC),GJ(NC),GK(NC),VOLUME(NC),TEMPERATURE(NC),DENS(N_MATL,NC), &
 BINS(NB,N_MATL,NC),REFERENCE(N_MATL,NC),CONSUMED(N_MATL,NC),MAT_RATE(N_MATL,NC), &
 GAS_TOTAL(N_TRACKED_SPECIES,NC),GAS_RATE(N_TRACKED_SPECIES,NC),HEAT_TOTAL(NC),HEAT_RATE(NC),CAP(N_MATL,NC), &
 COVER(3,NC),ROUTE(NC),TEMP_WEIGHT(NC),COUNTS(NC),CELL_BOXES(6,NC))
VOLUME=0; TEMPERATURE=0; DENS=0; BINS=0; REFERENCE=0; CONSUMED=0
MAT_RATE=0; GAS_TOTAL=0; GAS_RATE=0; HEAT_TOTAL=0; HEAT_RATE=0; CAP=HUGE(1._EB)
COVER=0; ROUTE=0; TEMP_WEIGHT=0; COUNTS=0; CELL_BOXES=0
DO NM=1,NMESHES
 DO KK=1,MESHES(NM)%KBAR; DO JJ=1,MESHES(NM)%JBAR; DO II=1,MESHES(NM)%IBAR
  ID=CELL_ID(NM,II,JJ,KK); OWNER(ID)=NM; GI(ID)=II; GJ(ID)=JJ; GK(ID)=KK
 ENDDO; ENDDO; ENDDO
ENDDO
DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
 G=>MESHES(NM)
 CALL CHECK(G%N_THIN_WALL_CELLS==0,'thin-wall reconstruction is not supported by the fixed-volume adapter')
 DO IW=1,G%N_EXTERNAL_WALL_CELLS+G%N_INTERNAL_WALL_CELLS
  WC=>G%WALL(IW); SF=>SURFACE(WC%SURF_INDEX)
  IF (.NOT.SF%EAE_HT3D.OR.WC%BOUNDARY_TYPE/=SOLID_BOUNDARY) CYCLE
  CALL CHECK(SF%HT_DIM==3.AND..NOT.SF%VARIABLE_THICKNESS.AND..NOT.SF%LINING.AND. &
     SF%GEOMETRY==SURF_CARTESIAN,'requires fixed Cartesian HT3D, without linings')
  CALL CHECK(SF%BACKING==EXPOSED.AND.SF%LAYER_DIVIDE<0._EB,'requires exposed backing and midpoint mass routing')
  CALL CHECK(ALL(SF%HT3D_WEIGHT>0._EB).AND.ABS(SUM(SF%HT3D_WEIGHT)-1._EB)<1.E-12_EB,'requires positive normalized directional weights')
  OD=>G%BOUNDARY_ONE_D(WC%OD_INDEX); BC=>G%BOUNDARY_COORD(WC%BC_INDEX)
  CALL CHECK(ALL(OD%MIN_LAYER_MASS==0._EB).AND.ALL(OD%MIN_LAYER_THICKNESS==0._EB), &
     'positive layer-removal thresholds are unsupported; set both minimum fractions and thicknesses to zero')
  DO N=1,OD%N_MATL
   M=OD%MATL_INDEX(N); ML=>MATERIAL(M)
   CALL CHECK(.NOT.ML%ALLOW_SHRINKING.AND..NOT.ML%ALLOW_SWELLING,'shrink/swell requires a conservative moving-volume remap')
   CALL CHECK(ML%N_REACTIONS==0.OR.ML%EAE%ENABLED,'legacy reactive material inside coupled solid is unsupported')
   IF (.NOT.ML%EAE%ENABLED) CYCLE
   YC=SUM(ML%NU_RESIDUE(1:ML%N_RESIDUE(1),1))
   CALL CHECK(YC>0._EB,'requires a persistent inert residue matrix after virgin burnout')
   CALL CHECK(ALL(ML%NU_GAS(:,1)>=0._EB).AND.ABS(YC+SUM(ML%NU_GAS(:,1))-1._EB)<1.E-10_EB, &
      'solid and gas mass yields must be nonnegative and sum to one')
   CALL CHECK(ALL(ABS(ML%ADJUST_BURN_RATE(:,1)-1._EB)<1.E-12_EB),'gas burn-rate adjustment is unsupported')
  ENDDO
  DO I=1,SUM(OD%N_LAYER_CELLS(1:OD%N_LAYERS))
   NODE=>G%BOUNDARY_THR_D(WC%TD_INDEX)%NODE(I)
   CALL CHECK(NODE%HT3D,'non-HT3D lining node in coupled column')
   NOM=NODE%MESH_NUMBER; II=NODE%I; JJ=NODE%J; KK=NODE%K
   ID=CELL_ID(NOM,II,JJ,KK); NODE%E3_CELL_ID=ID
   CALL NODE_BOX(BC,OD,I,BOX); VOL=(BOX(2)-BOX(1))*(BOX(4)-BOX(3))*(BOX(6)-BOX(5))
   CALL CHECK(VOL>0._EB,'nonpositive physical volume')
   COVER(ABS(BC%IOR),ID)=COVER(ABS(BC%IOR),ID)+1._EB
   ROUTE(ID)=ROUTE(ID)+SF%HT3D_WEIGHT(ABS(BC%IOR))*FRONT_FRACTION(OD,I)
   IF (NOM/=NM) CYCLE
   EXPECTED=[G%X(II-1),G%X(II),G%Y(JJ-1),G%Y(JJ),G%Z(KK-1),G%Z(KK)]
   CALL CHECK(MAXVAL(ABS(BOX-EXPECTED))<1.E-10_EB,'solid nodes must align one-to-one with physical Cartesian cells')
   RHO0=0
   DO N=1,OD%N_MATL
    RHO0(OD%MATL_INDEX(N))=OD%MATL_COMP(N)%RHO(I)
    IF (MATERIAL(OD%MATL_INDEX(N))%EAE%ENABLED) &
       CAP(OD%MATL_INDEX(N),ID)=MIN(CAP(OD%MATL_INDEX(N),ID), &
          MATERIAL(OD%MATL_INDEX(N))%MAX_REACTION_RATE(1))
   ENDDO
   CALL CHECK(SF%MINIMUM_BURNOUT_TIME>=1.E5_EB,'finite minimum burnout time requires a separate supported cap adapter')
   IF (VOLUME(ID)>0._EB) THEN
    CALL CHECK(MAXVAL(ABS(RHO0-DENS(:,ID)))<1.E-9_EB,'directional initial material inventories disagree')
   ELSE
    VOLUME(ID)=VOL; DENS(:,ID)=RHO0; CELL_BOXES(:,ID)=EXPECTED
   ENDIF
   TEMP_WEIGHT(ID)=TEMP_WEIGHT(ID)+OD%TMP(I); COUNTS(ID)=COUNTS(ID)+1
  ENDDO
 ENDDO
ENDDO
CALL SUM_REAL(VOLUME); CALL SUM_REAL(TEMP_WEIGHT); CALL SUM_REAL(COUNTS)
IF (N_MPI_PROCESSES>1) THEN
 CALL MPI_ALLREDUCE(MPI_IN_PLACE,DENS,SIZE(DENS),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
 CALL MPI_ALLREDUCE(MPI_IN_PLACE,CELL_BOXES,SIZE(CELL_BOXES),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
 CALL MPI_ALLREDUCE(MPI_IN_PLACE,COVER,SIZE(COVER),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
 CALL MPI_ALLREDUCE(MPI_IN_PLACE,CAP,SIZE(CAP),MPI_DOUBLE_PRECISION,MPI_MIN,MPI_COMM_WORLD,IE)
ENDIF
CALL SUM_REAL(ROUTE)
CALL CHECK(COUNT(VOLUME>0._EB)>0,'no supported physical volume cells found')
DO ID=1,NC
 IF (VOLUME(ID)<=0._EB) THEN
  CALL CHECK(ALL(COVER(:,ID)==0._EB),'mapped column cell has no authoritative mesh owner'); CYCLE
 ENDIF
 CALL CHECK(ALL(ABS(COVER(:,ID)-2._EB)<1.E-12_EB),'every volume requires exactly two exposed column views per axis')
 CALL CHECK(ABS(ROUTE(ID)-1._EB)<1.E-12_EB,'directional gas routing does not sum to one physical source')
 TEMPERATURE(ID)=TEMP_WEIGHT(ID)/COUNTS(ID)
 REFERENCE(:,ID)=DENS(:,ID)*VOLUME(ID)
 DO M=1,N_MATL
  IF (.NOT.MATERIAL(M)%EAE%ENABLED) CYCLE
  NN=MATERIAL(M)%EAE%NN
  BINS(1:NN,M,ID)=REFERENCE(M,ID)*MATERIAL(M)%EAE%WEIGHT
 ENDDO
ENDDO
! All overlapping views, including foreign-mesh segments, must describe the
! same physical initial state. Reject ambiguity before any canonical projection.
DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
 G=>MESHES(NM)
 DO IW=1,G%N_EXTERNAL_WALL_CELLS+G%N_INTERNAL_WALL_CELLS
  WC=>G%WALL(IW)
  IF (.NOT.SURFACE(WC%SURF_INDEX)%EAE_HT3D.OR.WC%BOUNDARY_TYPE/=SOLID_BOUNDARY) CYCLE
  OD=>G%BOUNDARY_ONE_D(WC%OD_INDEX); BC=>G%BOUNDARY_COORD(WC%BC_INDEX)
  DO I=1,SUM(OD%N_LAYER_CELLS(1:OD%N_LAYERS))
   ID=G%BOUNDARY_THR_D(WC%TD_INDEX)%NODE(I)%E3_CELL_ID
   CALL NODE_BOX(BC,OD,I,BOX)
   CALL CHECK(MAXVAL(ABS(BOX-CELL_BOXES(:,ID)))<1.E-10_EB,'cross-view physical geometry disagrees')
   RHO0=0
   DO N=1,OD%N_MATL
    RHO0(OD%MATL_INDEX(N))=OD%MATL_COMP(N)%RHO(I)
   ENDDO
   CALL CHECK(MAXVAL(ABS(RHO0-DENS(:,ID)))<1.E-9_EB,'cross-view initial material inventories disagree')
   CALL CHECK(IEEE_IS_FINITE(OD%TMP(I)).AND.ABS(OD%TMP(I)-TEMPERATURE(ID))<1.E-8_EB, &
      'cross-view initial temperatures disagree')
  ENDDO
 ENDDO
ENDDO
INITIAL_MASS=SUM(REFERENCE); E3_TIME=T_BEGIN; E3_READY=.TRUE.
CALL UPDATE_RATES
CALL E3_PROJECT
END SUBROUTINE
SUBROUTINE SYNC_STATE
INTEGER :: ID,IE
IF (N_MPI_PROCESSES==1) RETURN
DO ID=1,NC
 IF (PROCESS(OWNER(ID))==MY_RANK) CYCLE
 DENS(:,ID)=0; BINS(:,:,ID)=0; REFERENCE(:,ID)=0; CONSUMED(:,ID)=0
 MAT_RATE(:,ID)=0; GAS_TOTAL(:,ID)=0; GAS_RATE(:,ID)=0; HEAT_TOTAL(ID)=0; HEAT_RATE(ID)=0; TEMPERATURE(ID)=0
ENDDO
CALL MPI_ALLREDUCE(MPI_IN_PLACE,DENS,SIZE(DENS),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
CALL MPI_ALLREDUCE(MPI_IN_PLACE,BINS,SIZE(BINS),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
CALL MPI_ALLREDUCE(MPI_IN_PLACE,REFERENCE,SIZE(REFERENCE),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
CALL MPI_ALLREDUCE(MPI_IN_PLACE,CONSUMED,SIZE(CONSUMED),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
CALL MPI_ALLREDUCE(MPI_IN_PLACE,MAT_RATE,SIZE(MAT_RATE),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
CALL MPI_ALLREDUCE(MPI_IN_PLACE,GAS_TOTAL,SIZE(GAS_TOTAL),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
CALL MPI_ALLREDUCE(MPI_IN_PLACE,GAS_RATE,SIZE(GAS_RATE),MPI_DOUBLE_PRECISION,MPI_SUM,MPI_COMM_WORLD,IE)
CALL SUM_REAL(HEAT_TOTAL); CALL SUM_REAL(HEAT_RATE); CALL SUM_REAL(TEMPERATURE)
END SUBROUTINE
SUBROUTINE E3_ADVANCE(T,DT)
REAL(EB),INTENT(IN) :: T,DT
INTEGER :: ID,M,NN,J,R,IT
REAL(EB) :: LOSS(EAE_MAX_NODES),BEFORE,REQUEST,F,ACTUAL,OLD_DENS(N_MATL)
TYPE(MATERIAL_TYPE),POINTER :: ML
IF (.NOT.E3_READY) RETURN
CALL CHECK(DT>0._EB.AND.ABS(T-DT-E3_TIME)<1.E-9_EB,'wall interval and physical inventory clock disagree')
DO ID=1,NC
 IF (VOLUME(ID)<=0._EB.OR.PROCESS(OWNER(ID))/=MY_RANK) CYCLE
 OLD_DENS=DENS(:,ID)
 GAS_RATE(:,ID)=0; HEAT_RATE(ID)=0
 DO M=1,N_MATL
  ML=>MATERIAL(M); IF (.NOT.ML%EAE%ENABLED) CYCLE
  NN=ML%EAE%NN; BEFORE=SUM(BINS(1:NN,M,ID))
  IF (BEFORE<=0._EB) CYCLE
  CALL EAE_TRIAL(ML%EAE,BINS(1:NN,M,ID),TEMPERATURE(ID),DT,LOSS(1:NN))
  REQUEST=SUM(LOSS(1:NN)); IF (REQUEST<=0._EB) CYCLE
  F=MIN(1._EB,CAP(M,ID)*VOLUME(ID)*DT/REQUEST,BEFORE/REQUEST)
  BINS(1:NN,M,ID)=MAX(0._EB,BINS(1:NN,M,ID)-F*LOSS(1:NN))
  ACTUAL=BEFORE-SUM(BINS(1:NN,M,ID))
  DENS(M,ID)=SUM(BINS(1:NN,M,ID))/VOLUME(ID)
  CONSUMED(M,ID)=CONSUMED(M,ID)+ACTUAL
  DO J=1,ML%N_RESIDUE(1)
   R=ML%RESIDUE_MATL_INDEX(J,1)
   DENS(R,ID)=DENS(R,ID)+ML%NU_RESIDUE(J,1)*ACTUAL/VOLUME(ID)
  ENDDO
  GAS_TOTAL(:,ID)=GAS_TOTAL(:,ID)+ML%NU_GAS(:,1)*ACTUAL
  GAS_RATE(:,ID)=GAS_RATE(:,ID)+ML%NU_GAS(:,1)*ACTUAL/(VOLUME(ID)*DT)
  IT=MIN(I_MAX_TEMP,MAX(0,NINT(TEMPERATURE(ID))))
  HEAT_RATE(ID)=HEAT_RATE(ID)-ACTUAL*ML%H_R(1,IT)/(VOLUME(ID)*DT)
 ENDDO
 MAT_RATE(:,ID)=(DENS(:,ID)-OLD_DENS)/DT
 HEAT_TOTAL(ID)=HEAT_TOTAL(ID)+HEAT_RATE(ID)*VOLUME(ID)*DT
 CALL CHECK(ALL(DENS(:,ID)>=0._EB).AND.ALL(IEEE_IS_FINITE(DENS(:,ID))),'invalid accepted physical material state')
ENDDO
E3_TIME=T; CALL SYNC_STATE; CALL UPDATE_RATES; CALL E3_PROJECT
END SUBROUTINE
SUBROUTINE UPDATE_RATES
! Pointwise physical flux at the current kinetic state, for the gas solver's RK stages.
! Accepted interval consumption stays separate in the extensive mass/heat ledgers.
INTEGER :: ID,M,J,R,NN
REAL(EB) :: RATE
TYPE(MATERIAL_TYPE),POINTER :: ML
GAS_RATE=0._EB; MAT_RATE=0._EB
DO ID=1,NC
 IF (VOLUME(ID)<=0._EB) CYCLE
 DO M=1,N_MATL
  ML=>MATERIAL(M); IF (.NOT.ML%EAE%ENABLED) CYCLE
  NN=ML%EAE%NN
  RATE=SUM(ML%EAE%A*EXP(-ML%EAE%ENERGY/(8.314462618_EB*TEMPERATURE(ID)))*BINS(1:NN,M,ID))/VOLUME(ID)
  RATE=MIN(RATE,CAP(M,ID))
  MAT_RATE(M,ID)=MAT_RATE(M,ID)-RATE
  DO J=1,ML%N_RESIDUE(1)
   R=ML%RESIDUE_MATL_INDEX(J,1)
   MAT_RATE(R,ID)=MAT_RATE(R,ID)+ML%NU_RESIDUE(J,1)*RATE
  ENDDO
  GAS_RATE(:,ID)=GAS_RATE(:,ID)+ML%NU_GAS(:,1)*RATE
 ENDDO
ENDDO
END SUBROUTINE
SUBROUTINE E3_PROJECT
INTEGER :: NM,IW,I,N,M,ID,NN,NWP
REAL(EB) :: DX,OLD_FIRST,OLD_LAST
TYPE(MESH_TYPE),POINTER :: G
TYPE(WALL_TYPE),POINTER :: WC
TYPE(BOUNDARY_ONE_D_TYPE),POINTER :: OD
IF (.NOT.E3_READY) RETURN
DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
 G=>MESHES(NM)
 DO IW=1,G%N_EXTERNAL_WALL_CELLS+G%N_INTERNAL_WALL_CELLS
  WC=>G%WALL(IW)
  IF (.NOT.SURFACE(WC%SURF_INDEX)%EAE_HT3D.OR.WC%BOUNDARY_TYPE/=SOLID_BOUNDARY) CYCLE
  OD=>G%BOUNDARY_ONE_D(WC%OD_INDEX); NWP=SUM(OD%N_LAYER_CELLS(1:OD%N_LAYERS))
  CALL CHECK(NWP==SIZE(G%BOUNDARY_THR_D(WC%TD_INDEX)%NODE),'unsupported reconstruction changed physical noding')
  OLD_FIRST=OD%TMP(1); OLD_LAST=OD%TMP(NWP)
  DO N=1,OD%N_MATL
   M=OD%MATL_INDEX(N)
   IF (MATERIAL(M)%EAE%ENABLED) THEN
    IF (.NOT.ALLOCATED(OD%MATL_COMP(N)%EAE%MASS)) CALL EAE_ALLOCATE(OD%MATL_COMP(N)%EAE,MATERIAL(M)%EAE,OD%N_CELLS_MAX)
   ENDIF
   DO I=1,NWP
    ID=G%BOUNDARY_THR_D(WC%TD_INDEX)%NODE(I)%E3_CELL_ID
    CALL CHECK(ID>0.AND.VOLUME(ID)>0._EB,'unmapped reconstructed node')
    OD%MATL_COMP(N)%RHO(I)=DENS(M,ID); OD%TMP(I)=TEMPERATURE(ID)
    IF (.NOT.MATERIAL(M)%EAE%ENABLED) CYCLE
    DX=OD%X(I)-OD%X(I-1); NN=MATERIAL(M)%EAE%NN
    OD%MATL_COMP(N)%EAE%MASS(1:NN,I)=BINS(1:NN,M,ID)*DX/VOLUME(ID)
    OD%MATL_COMP(N)%EAE%REFERENCE(I)=REFERENCE(M,ID)*DX/VOLUME(ID)
    OD%MATL_COMP(N)%EAE%TRIAL(:,I)=0
   ENDDO
  ENDDO
  OD%TMP(0)=OD%TMP(0)+OD%TMP(1)-OLD_FIRST
  OD%TMP(NWP+1)=OD%TMP(NWP+1)+OD%TMP(NWP)-OLD_LAST
 ENDDO
 DO ID=OFFSET(NM)+1,OFFSET(NM)+G%IBAR*G%JBAR*G%KBAR
  IF (VOLUME(ID)>0._EB) G%TMP(GI(ID),GJ(ID),GK(ID))=TEMPERATURE(ID)
 ENDDO
ENDDO
END SUBROUTINE
REAL(EB) FUNCTION E3_HEAT(NM,IW,I) RESULT(Q)
INTEGER,INTENT(IN) :: NM,IW,I
INTEGER :: ID
ID=MESHES(NM)%BOUNDARY_THR_D(MESHES(NM)%WALL(IW)%TD_INDEX)%NODE(I)%E3_CELL_ID
Q=HEAT_RATE(ID)
END FUNCTION
SUBROUTINE E3_FLUX(NM,IW)
INTEGER,INTENT(IN) :: NM,IW
INTEGER :: I,ID,NWP,N
REAL(EB) :: DX,W,H_G,H_S
TYPE(WALL_TYPE),POINTER :: WC
TYPE(BOUNDARY_ONE_D_TYPE),POINTER :: OD
TYPE(BOUNDARY_COORD_TYPE),POINTER :: BC
TYPE(BOUNDARY_PROP1_TYPE),POINTER :: B1
TYPE(SURFACE_TYPE),POINTER :: SF
IF (.NOT.E3_READY) RETURN
WC=>MESHES(NM)%WALL(IW); SF=>SURFACE(WC%SURF_INDEX)
IF (.NOT.SF%EAE_HT3D.OR.WC%BOUNDARY_TYPE/=SOLID_BOUNDARY) RETURN
OD=>MESHES(NM)%BOUNDARY_ONE_D(WC%OD_INDEX); BC=>MESHES(NM)%BOUNDARY_COORD(WC%BC_INDEX)
B1=>MESHES(NM)%BOUNDARY_PROP1(WC%B1_INDEX)
B1%M_DOT_G_PP_ACTUAL=0; B1%M_DOT_G_PP_ADJUST=0; B1%Q_DOT_G_PP=0
OD%M_DOT_S_PP=0
NWP=SUM(OD%N_LAYER_CELLS(1:OD%N_LAYERS))
DO I=1,NWP
 ID=MESHES(NM)%BOUNDARY_THR_D(WC%TD_INDEX)%NODE(I)%E3_CELL_ID
 DX=OD%X(I)-OD%X(I-1); W=SF%HT3D_WEIGHT(ABS(BC%IOR))*FRONT_FRACTION(OD,I)*DX
 B1%M_DOT_G_PP_ACTUAL=B1%M_DOT_G_PP_ACTUAL+W*GAS_RATE(:,ID)
 DO N=1,OD%N_MATL
  OD%M_DOT_S_PP(N)=OD%M_DOT_S_PP(N)+W*MAT_RATE(OD%MATL_INDEX(N),ID)
 ENDDO
 ! Native gas sensible-enthalpy exchange is evaluated at the physical cell temperature.
 CALL GET_SENSIBLE_ENTHALPY(GAS_RATE(:,ID),H_G,B1%TMP_G)
 CALL GET_SENSIBLE_ENTHALPY(GAS_RATE(:,ID),H_S,TEMPERATURE(ID))
 B1%Q_DOT_G_PP=B1%Q_DOT_G_PP+W*(H_G-H_S)
ENDDO
B1%M_DOT_G_PP_ADJUST=B1%M_DOT_G_PP_ACTUAL
! Native pyrolysis activates this boundary when accepted material emits gas.
! With chemistry outside the column solver, perform that same activation here.
IF (SUM(B1%M_DOT_G_PP_ACTUAL)>0._EB) B1%T_IGN=MIN(B1%T_IGN,E3_TIME)
END SUBROUTINE
SUBROUTINE E3_CAPTURE
INTEGER :: NM,IW,I,ID,DIR,NWP,IE
REAL(EB),ALLOCATABLE :: SUM_T(:),COUNT_T(:)
TYPE(MESH_TYPE),POINTER :: G
TYPE(WALL_TYPE),POINTER :: WC
TYPE(BOUNDARY_ONE_D_TYPE),POINTER :: OD
IF (.NOT.E3_READY) RETURN
ALLOCATE(SUM_T(NC),COUNT_T(NC)); SUM_T=0; COUNT_T=0
DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
 G=>MESHES(NM); DIR=G%HT_3D_SWEEP_DIRECTION
 DO IW=1,G%N_EXTERNAL_WALL_CELLS+G%N_INTERNAL_WALL_CELLS
  WC=>G%WALL(IW)
  IF (.NOT.SURFACE(WC%SURF_INDEX)%EAE_HT3D.OR.WC%BOUNDARY_TYPE/=SOLID_BOUNDARY) CYCLE
  IF (ABS(G%BOUNDARY_COORD(WC%BC_INDEX)%IOR)/=DIR) CYCLE
  OD=>G%BOUNDARY_ONE_D(WC%OD_INDEX); NWP=SUM(OD%N_LAYER_CELLS(1:OD%N_LAYERS))
  DO I=1,NWP
   ID=G%BOUNDARY_THR_D(WC%TD_INDEX)%NODE(I)%E3_CELL_ID
   SUM_T(ID)=SUM_T(ID)+OD%TMP(I); COUNT_T(ID)=COUNT_T(ID)+1
  ENDDO
 ENDDO
ENDDO
CALL SUM_REAL(SUM_T); CALL SUM_REAL(COUNT_T)
DO ID=1,NC
 IF (VOLUME(ID)<=0._EB) CYCLE
 CALL CHECK(ABS(COUNT_T(ID)-2._EB)<1.E-12_EB,'active directional temperature coverage changed')
 TEMPERATURE(ID)=SUM_T(ID)/COUNT_T(ID)
 CALL CHECK(IEEE_IS_FINITE(TEMPERATURE(ID)).AND.TEMPERATURE(ID)>0._EB,'invalid physical temperature')
ENDDO
CALL UPDATE_RATES
CALL E3_PROJECT
END SUBROUTINE
SUBROUTINE E3_DUMP(LU,NM)
INTEGER,INTENT(IN) :: LU,NM
INTEGER :: ID,N
IF (.NOT.E3_READY) RETURN
N=COUNT(VOLUME>0._EB.AND.OWNER==NM)
WRITE(LU) 'E3VOL003',N,N_MATL,NB,NC,N_TRACKED_SPECIES,E3_TIME
