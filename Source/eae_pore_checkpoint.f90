! Experimental retained-body checkpoint. Fixed topology/identity only.
! Not yet the native FDS dump/MPI integration or a moving-geometry format.
MODULE EAE_PORE_CHECKPOINT
USE PRECISION_PARAMETERS,ONLY: EB
USE EAE_RETAINED_BODY,ONLY: RETAINED_BODY
USE EAE_PORE_LTE,ONLY: MATRIX_POROSITY
USE,INTRINSIC :: ISO_FORTRAN_ENV,ONLY: INT64
USE,INTRINSIC :: IEEE_ARITHMETIC,ONLY: IEEE_IS_FINITE
IMPLICIT NONE
PRIVATE
PUBLIC :: WRITE_PORE_CHECKPOINT,READ_PORE_CHECKPOINT
CHARACTER(24),PARAMETER :: TAG='EAE_PORE_FIXED_TOPOLOGY_1',ENDTAG='EAE_PORE_CHECKPOINT_END_1'
CONTAINS
SUBROUTINE CONFIG_BYTES(B,DATA,IERR)
TYPE(RETAINED_BODY),INTENT(IN) :: B
CHARACTER,ALLOCATABLE,INTENT(OUT) :: DATA(:)
INTEGER,INTENT(OUT) :: IERR
INTEGER :: U,I,S,N
IERR=1
OPEN(NEWUNIT=U,STATUS='SCRATCH',ACCESS='STREAM',FORM='UNFORMATTED',IOSTAT=S)
IF(S/=0) RETURN
WRITE(U,IOSTAT=S) B%NM,B%NS,B%NC,B%NB,B%NT,B%NP,B%PREF,B%NODE_UID,B%BOXES,B%VM,B%RHO,B%US,B%HG,B%RG, &
 B%YS,B%YG,B%CAP,B%LEFT,B%RIGHT,B%CONDUCTANCE
IF(S==0) THEN
 DO I=1,B%NM
  WRITE(U,IOSTAT=S) B%KINETICS(I)%ENABLED,B%KINETICS(I)%K,B%KINETICS(I)%NN,B%KINETICS(I)%A, &
    B%KINETICS(I)%EMIN,B%KINETICS(I)%EMAX
  IF(S/=0) EXIT
  IF(B%KINETICS(I)%ENABLED) THEN
   WRITE(U,IOSTAT=S) B%KINETICS(I)%ENERGY,B%KINETICS(I)%WEIGHT
   IF(S/=0) EXIT
  ENDIF
 ENDDO
ENDIF
IF(S==0) THEN
 INQUIRE(UNIT=U,SIZE=N,IOSTAT=S)
 IF(S==0) THEN
  ALLOCATE(DATA(N));READ(U,POS=1,IOSTAT=S) DATA
 ENDIF
ENDIF
CLOSE(U);IF(S==0) IERR=0
END SUBROUTINE
SUBROUTINE STATE_BYTES(B,DATA,IERR)
TYPE(RETAINED_BODY),INTENT(IN) :: B
CHARACTER,ALLOCATABLE,INTENT(OUT) :: DATA(:)
INTEGER,INTENT(OUT) :: IERR
INTEGER :: U,S,N
IERR=1
OPEN(NEWUNIT=U,STATUS='SCRATCH',ACCESS='STREAM',FORM='UNFORMATTED',IOSTAT=S)
IF(S/=0) RETURN
WRITE(U,IOSTAT=S) B%TIME,B%SOLID,B%PORE,B%BINS,B%INITIAL_REF,B%BORN_REF,B%CONSUMED,B%GENERATED, &
 B%ENERGY,B%T,B%P,B%VP,B%PHI,B%REFERENCE_HEAT,B%ARCHIVE,B%PORT_P,B%PORT_T,B%PORT_Y,B%PORT_LEDGER
IF(S==0) THEN
 INQUIRE(UNIT=U,SIZE=N,IOSTAT=S)
 IF(S==0) THEN
  ALLOCATE(DATA(N));READ(U,POS=1,IOSTAT=S) DATA
 ENDIF
ENDIF
CLOSE(U);IF(S==0) IERR=0
END SUBROUTINE
INTEGER(INT64) FUNCTION CRC64(A,B) RESULT(CRC)
CHARACTER,INTENT(IN) :: A(:),B(:)
INTEGER :: I,J,K,V
CRC=0_INT64
DO K=1,2
 DO I=1,MERGE(SIZE(A),SIZE(B),K==1)
  IF(K==1) THEN
   V=IACHAR(A(I))
  ELSE
   V=IACHAR(B(I))
  ENDIF
  CRC=IEOR(CRC,ISHFT(INT(V,INT64),56))
  DO J=1,8
   IF(BTEST(CRC,63)) THEN
    CRC=IEOR(ISHFT(CRC,1),INT(Z'42F0E1EBA9EA3693',INT64))
   ELSE
    CRC=ISHFT(CRC,1)
   ENDIF
  ENDDO
 ENDDO
ENDDO
END FUNCTION
SUBROUTINE VALIDATE_STATE(B,IERR)
TYPE(RETAINED_BODY),INTENT(IN) :: B
INTEGER,INTENT(OUT) :: IERR
INTEGER :: I,M,J,S
REAL(EB) :: VP,PHI,E,P,T,F
IERR=1
IF(.NOT.B%READY.OR..NOT.IEEE_IS_FINITE(B%TIME).OR.B%TIME<0) RETURN
IF(.NOT.ALL(IEEE_IS_FINITE(B%SOLID)).OR..NOT.ALL(IEEE_IS_FINITE(B%PORE)).OR..NOT.ALL(IEEE_IS_FINITE(B%BINS))) RETURN
IF(.NOT.ALL(IEEE_IS_FINITE(B%INITIAL_REF)).OR..NOT.ALL(IEEE_IS_FINITE(B%BORN_REF)).OR..NOT.ALL(IEEE_IS_FINITE(B%CONSUMED))) RETURN
IF(.NOT.ALL(IEEE_IS_FINITE(B%GENERATED)).OR..NOT.ALL(IEEE_IS_FINITE(B%ENERGY)).OR..NOT.ALL(IEEE_IS_FINITE(B%T))) RETURN
IF(.NOT.ALL(IEEE_IS_FINITE(B%P)).OR..NOT.ALL(IEEE_IS_FINITE(B%VP)).OR..NOT.ALL(IEEE_IS_FINITE(B%PHI))) RETURN
IF(.NOT.ALL(IEEE_IS_FINITE(B%REFERENCE_HEAT)).OR..NOT.ALL(IEEE_IS_FINITE(B%ARCHIVE))) RETURN
IF(.NOT.ALL(IEEE_IS_FINITE(B%PORT_P)).OR..NOT.ALL(IEEE_IS_FINITE(B%PORT_T)).OR..NOT.ALL(IEEE_IS_FINITE(B%PORT_Y))) RETURN
IF(.NOT.ALL(IEEE_IS_FINITE(B%PORT_LEDGER))) RETURN
IF(ANY(B%SOLID<0).OR.ANY(B%PORE<0).OR.ANY(B%BINS<0).OR.ANY(B%INITIAL_REF<0).OR.ANY(B%BORN_REF<0)) RETURN
IF(ANY(B%CONSUMED<0).OR.ANY(B%GENERATED<0).OR.ANY(B%PORT_Y<0).OR.ANY(B%PORT_P<=0)) RETURN
IF(ANY(B%PORT_T<=0).OR.ANY(B%PORT_T>B%NT)) RETURN
DO I=1,B%NP
 IF(ABS(SUM(B%PORT_Y(:,I))-1._EB)>32*EPSILON(1._EB)) RETURN
ENDDO
DO I=1,B%NC
 DO M=1,B%NM
  IF(B%KINETICS(M)%ENABLED) THEN
   IF(ABS(SUM(B%BINS(:,M,I))-B%SOLID(M,I))>1.E-12_EB) RETURN
  ELSE
   IF(ANY(B%BINS(:,M,I)/=0).OR.B%CONSUMED(M,I)/=0) RETURN
  ENDIF
  IF(ABS(B%SOLID(M,I)+B%CONSUMED(M,I)-B%INITIAL_REF(M,I)-B%BORN_REF(M,I))>1.E-12_EB) RETURN
 ENDDO
 CALL MATRIX_POROSITY(B%SOLID(:,I),B%RHO,B%VM(I),VP,PHI,S)
 IF(S/=0) RETURN
 IF(ABS(VP-B%VP(I))>32*EPSILON(1._EB)*B%VM(I).OR.ABS(PHI-B%PHI(I))>32*EPSILON(1._EB)) RETURN
 T=B%T(I);IF(T<=0.OR.T>B%NT) RETURN
 J=MIN(B%NT-1,INT(T));F=T-J
 E=SUM(B%SOLID(:,I)*(B%US(J,:)+F*(B%US(J+1,:)-B%US(J,:))))+ &
   SUM(B%PORE(:,I)*(B%UG(J,:)+F*(B%UG(J+1,:)-B%UG(J,:))))
 IF(ABS(E-B%ENERGY(I))>1.E-10_EB*MAX(1._EB,ABS(E),ABS(B%ENERGY(I)))) RETURN
 P=0
 IF(VP>0) THEN
  P=SUM(B%PORE(:,I)*B%RG)*T/VP
 ELSE
  IF(SUM(B%PORE(:,I))>0) RETURN
 ENDIF
 IF(ABS(P-B%P(I))>1.E-10_EB*MAX(1._EB,P)) RETURN
ENDDO
IERR=0
END SUBROUTINE
SUBROUTINE WRITE_PORE_CHECKPOINT(B,PATH,IERR)
TYPE(RETAINED_BODY),INTENT(IN) :: B
CHARACTER(*),INTENT(IN) :: PATH
INTEGER,INTENT(OUT) :: IERR
CHARACTER,ALLOCATABLE :: CONFIG(:),STATE(:)
INTEGER :: U,S
IERR=1
CALL VALIDATE_STATE(B,S);IF(S/=0) RETURN
CALL CONFIG_BYTES(B,CONFIG,S);IF(S/=0) RETURN
CALL STATE_BYTES(B,STATE,S);IF(S/=0) RETURN
! STATUS=NEW never overwrites any existing checkpoint.
OPEN(NEWUNIT=U,FILE=PATH,STATUS='NEW',ACCESS='STREAM',FORM='UNFORMATTED',IOSTAT=S)
IF(S/=0) RETURN
WRITE(U,IOSTAT=S) TAG,1,STORAGE_SIZE(1._EB),STORAGE_SIZE(1),SIZE(CONFIG),SIZE(STATE),CONFIG,STATE,CRC64(CONFIG,STATE),ENDTAG
CLOSE(U);IF(S==0) IERR=0
END SUBROUTINE
SUBROUTINE READ_PORE_CHECKPOINT(B,PATH,IERR)
TYPE(RETAINED_BODY),INTENT(INOUT) :: B
CHARACTER(*),INTENT(IN) :: PATH
INTEGER,INTENT(OUT) :: IERR
TYPE(RETAINED_BODY) :: C
CHARACTER,ALLOCATABLE :: EXPECTED(:),TEMPLATE(:),CONFIG(:),STATE(:)
CHARACTER(24) :: START,FINISH
INTEGER(INT64) :: CRC,FILESIZE,EXPECTED_SIZE
INTEGER :: U,S,V,RBITS,IBITS,NCONFIG,NSTATE
IERR=1
IF(.NOT.B%READY) RETURN
CALL CONFIG_BYTES(B,EXPECTED,S);IF(S/=0) RETURN
CALL STATE_BYTES(B,TEMPLATE,S);IF(S/=0) RETURN
OPEN(NEWUNIT=U,FILE=PATH,STATUS='OLD',ACCESS='STREAM',FORM='UNFORMATTED',IOSTAT=S)
IF(S/=0) RETURN
READ(U,IOSTAT=S) START,V,RBITS,IBITS,NCONFIG,NSTATE
IF(S/=0) THEN
 CLOSE(U);RETURN
ENDIF
IERR=2
IF(START/=TAG.OR.V/=1.OR.RBITS/=STORAGE_SIZE(1._EB).OR.IBITS/=STORAGE_SIZE(1)) THEN
 CLOSE(U);RETURN
ENDIF
IF(NCONFIG/=SIZE(EXPECTED).OR.NSTATE/=SIZE(TEMPLATE)) THEN
 CLOSE(U);RETURN
ENDIF
INQUIRE(UNIT=U,SIZE=FILESIZE,IOSTAT=S)
EXPECTED_SIZE=48_INT64+5_INT64*STORAGE_SIZE(1)/8+8_INT64+SIZE(EXPECTED,KIND=INT64)+SIZE(TEMPLATE,KIND=INT64)
IF(S/=0.OR.FILESIZE/=EXPECTED_SIZE) THEN
 CLOSE(U);RETURN
ENDIF
! Allocation uses locally verified configuration sizes, never untrusted sizes.
ALLOCATE(CONFIG(SIZE(EXPECTED)),STATE(SIZE(TEMPLATE)))
READ(U,IOSTAT=S) CONFIG,STATE,CRC,FINISH
CLOSE(U)
IERR=3
IF(S/=0) RETURN
IF(FINISH/=ENDTAG.OR.CRC/=CRC64(CONFIG,STATE).OR.ANY(CONFIG/=EXPECTED)) RETURN
C=B
OPEN(NEWUNIT=U,STATUS='SCRATCH',ACCESS='STREAM',FORM='UNFORMATTED',IOSTAT=S)
IF(S/=0) RETURN
WRITE(U,IOSTAT=S) STATE
IF(S==0) READ(U,POS=1,IOSTAT=S) C%TIME,C%SOLID,C%PORE,C%BINS,C%INITIAL_REF,C%BORN_REF,C%CONSUMED,C%GENERATED, &
 C%ENERGY,C%T,C%P,C%VP,C%PHI,C%REFERENCE_HEAT,C%ARCHIVE,C%PORT_P,C%PORT_T,C%PORT_Y,C%PORT_LEDGER
CLOSE(U)
IF(S/=0) RETURN
CALL VALIDATE_STATE(C,S);IERR=4
IF(S/=0) RETURN
B=C;IERR=0
END SUBROUTINE
END MODULE
