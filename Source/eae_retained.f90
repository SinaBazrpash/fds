! Persistent, retained-matrix EAE/LTE/pore state. Native FDS adapter is separate.
! Geometry is NEVER changed by a numerical mass threshold in this module.
MODULE EAE_RETAINED_BODY
USE PRECISION_PARAMETERS,ONLY: EB
USE EAE_DAEM
USE EAE_PORE_LTE,ONLY: MATRIX_POROSITY
USE EAE_PORE_NETWORK,ONLY: EQUILIBRATE_PORE_NETWORK
USE EAE_CONSERVATIVE_REMAP,ONLY: MIXTURE_TEMPERATURE
USE,INTRINSIC :: IEEE_ARITHMETIC,ONLY: IEEE_IS_FINITE
IMPLICIT NONE
PRIVATE
PUBLIC :: RETAINED_BODY,CONFIGURE_BODY,ADVANCE_BODY
TYPE RETAINED_BODY
 INTEGER :: NM=0,NS=0,NC=0,NB=0,NT=0,NP=0
 LOGICAL :: READY=.FALSE.
 TYPE(EAE_CONFIG),ALLOCATABLE :: KINETICS(:)
 REAL(EB),ALLOCATABLE :: SOLID(:,:),PORE(:,:),BINS(:,:,:),INITIAL_REF(:,:),BORN_REF(:,:),CONSUMED(:,:),GENERATED(:,:)
 REAL(EB),ALLOCATABLE :: ENERGY(:),T(:),P(:),VM(:),VP(:),PHI(:),RHO(:),US(:,:),HG(:,:),UG(:,:),RG(:)
 REAL(EB),ALLOCATABLE :: YS(:,:),YG(:,:),CAP(:),REFERENCE_HEAT(:,:),ARCHIVE(:,:),PORT_LEDGER(:,:)
 INTEGER,ALLOCATABLE :: LEFT(:),RIGHT(:),NODE_UID(:)
 REAL(EB),ALLOCATABLE :: BOXES(:,:)
 REAL(EB),ALLOCATABLE :: CONDUCTANCE(:),PORT_P(:),PORT_T(:),PORT_Y(:,:)
 REAL(EB) :: TIME=0._EB,PREF=0._EB
END TYPE
CONTAINS
REAL(EB) FUNCTION CONTENT(M,TAB,T) RESULT(E)
REAL(EB),INTENT(IN) :: M(:),TAB(0:,:),T
INTEGER :: I
I=MIN(UBOUND(TAB,1)-1,MAX(0,INT(T)))
E=SUM(M*(TAB(I,:)+(T-I)*(TAB(I+1,:)-TAB(I,:))))
END FUNCTION
SUBROUTINE CONFIGURE_BODY(B,KIN,SM,VM,RHO,US,HG,RG,PM,T0,YS,YG,LEFT,RIGHT,G,PP,PT,PY,PREF,UID,BOXES,IERR)
TYPE(RETAINED_BODY),INTENT(INOUT) :: B
TYPE(EAE_CONFIG),INTENT(IN) :: KIN(:)
REAL(EB),INTENT(IN) :: SM(:,:),VM(:),RHO(:),US(0:,:),HG(0:,:),RG(:),PM(:,:),T0(:),YS(:,:),YG(:,:),G(:),PP(:),PT(:),PY(:,:),PREF
INTEGER,INTENT(IN) :: LEFT(:),RIGHT(:),UID(:)
REAL(EB),INTENT(IN) :: BOXES(:,:)
INTEGER,INTENT(OUT) :: IERR
TYPE(RETAINED_BODY) :: C
INTEGER :: I,M,NM,NS,NC,NT,NN,STATUS,J
REAL(EB) :: VCHECK
IERR=1;NM=SIZE(KIN);NS=SIZE(RG);NC=SIZE(VM);NT=UBOUND(US,1)
IF (NM<1.OR.NS<1.OR.NC<1.OR.NT<1.OR.PREF<=0) RETURN
IF (SIZE(SM,1)/=NM.OR.SIZE(SM,2)/=NC.OR.SIZE(RHO)/=NM.OR.SIZE(T0)/=NC) RETURN
IF (SIZE(PM,1)/=NS.OR.SIZE(PM,2)/=NC.OR.SIZE(US,2)/=NM.OR.SIZE(HG,2)/=NS.OR.UBOUND(HG,1)/=NT) RETURN
IF (SIZE(YS,1)/=NM.OR.SIZE(YS,2)/=NM.OR.SIZE(YG,1)/=NS.OR.SIZE(YG,2)/=NM) RETURN
IF (SIZE(LEFT)/=SIZE(RIGHT).OR.SIZE(G)/=SIZE(LEFT).OR.SIZE(PP)/=SIZE(PT).OR.SIZE(PY,1)/=NS.OR.SIZE(PY,2)/=SIZE(PP)) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(SM)).OR..NOT.ALL(IEEE_IS_FINITE(PM)).OR..NOT.ALL(IEEE_IS_FINITE(T0))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(US)).OR..NOT.ALL(IEEE_IS_FINITE(HG)).OR..NOT.ALL(IEEE_IS_FINITE(RG))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(YS)).OR..NOT.ALL(IEEE_IS_FINITE(YG)).OR..NOT.ALL(IEEE_IS_FINITE(G))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(RHO)).OR..NOT.ALL(IEEE_IS_FINITE(VM)).OR..NOT.IEEE_IS_FINITE(PREF)) RETURN
IF (ANY(SM<0).OR.ANY(PM<0).OR.ANY(RHO<=0).OR.ANY(VM<=0).OR.ANY(RG<=0).OR.ANY(G<0)) RETURN
IF (ANY(YS<0).OR.ANY(YG<0).OR.ANY(T0<=0).OR.ANY(T0>NT)) RETURN
IF (ANY(LEFT<1).OR.ANY(LEFT>NC).OR.ANY(RIGHT==0).OR.ANY(RIGHT>NC).OR.ANY(RIGHT< -SIZE(PP)).OR.ANY(LEFT==RIGHT)) RETURN
IF (SIZE(UID)/=NC.OR.SIZE(BOXES,1)/=6.OR.SIZE(BOXES,2)/=NC) RETURN
IF (ANY(UID<=0).OR..NOT.ALL(IEEE_IS_FINITE(BOXES))) RETURN
DO I=1,NC
 IF (ANY(BOXES([2,4,6],I)<=BOXES([1,3,5],I))) RETURN
 VCHECK=PRODUCT(BOXES([2,4,6],I)-BOXES([1,3,5],I))
 IF (ABS(VCHECK-VM(I))>32*EPSILON(1._EB)*VM(I)) RETURN
 DO J=I+1,NC
  IF (UID(I)==UID(J)) RETURN
 ENDDO
ENDDO
C%NODE_UID=UID;C%BOXES=BOXES
C%NM=NM;C%NS=NS;C%NC=NC;C%NT=NT;C%NB=MAXVAL(KIN%NN);C%NP=SIZE(PP);C%PREF=PREF
C%KINETICS=KIN;C%SOLID=SM;C%PORE=PM;C%RHO=RHO;C%VM=VM;C%US=US;C%HG=HG;C%RG=RG;C%YS=YS;C%YG=YG
C%LEFT=LEFT;C%RIGHT=RIGHT;C%CONDUCTANCE=G;C%PORT_P=PP;C%PORT_T=PT;C%PORT_Y=PY
ALLOCATE(C%BINS(C%NB,NM,NC),C%INITIAL_REF(NM,NC),C%BORN_REF(NM,NC),C%CONSUMED(NM,NC),C%GENERATED(NS,NC), &
 C%ENERGY(NC),C%T(NC),C%P(NC),C%VP(NC),C%PHI(NC),C%UG(0:NT,NS),C%CAP(NM),C%REFERENCE_HEAT(NM,NC), &
 C%ARCHIVE(4*NM+NS,NC),C%PORT_LEDGER(NS+1,C%NP))
C%BINS=0;C%INITIAL_REF=SM;C%BORN_REF=0;C%CONSUMED=0;C%GENERATED=0;C%REFERENCE_HEAT=0;C%ARCHIVE=0;C%PORT_LEDGER=0;C%CAP=HUGE(1._EB)
DO I=0,NT;C%UG(I,:)=HG(I,:)-RG*REAL(I,EB);ENDDO
DO M=1,NM
 IF (.NOT.KIN(M)%ENABLED) CYCLE
 NN=KIN(M)%NN
 IF (NN<8.OR.NN>EAE_MAX_NODES.OR..NOT.ALLOCATED(KIN(M)%WEIGHT).OR..NOT.ALLOCATED(KIN(M)%ENERGY)) RETURN
 IF (SIZE(KIN(M)%WEIGHT)/=NN.OR.SIZE(KIN(M)%ENERGY)/=NN) RETURN
 IF (.NOT.ALL(IEEE_IS_FINITE(KIN(M)%WEIGHT)).OR.ANY(KIN(M)%WEIGHT<0)) RETURN
 IF (ABS(SUM(YS(:,M))+SUM(YG(:,M))-1._EB)>1.E-10_EB) RETURN
 IF (ABS(SUM(KIN(M)%WEIGHT)-1._EB)>32*EPSILON(1._EB)) RETURN
 DO I=1,NC
  C%BINS(1:NN,M,I)=SM(M,I)*KIN(M)%WEIGHT;C%INITIAL_REF(M,I)=SM(M,I)
 ENDDO
ENDDO
DO I=1,NC
 CALL MATRIX_POROSITY(SM(:,I),RHO,VM(I),C%VP(I),C%PHI(I),STATUS)
 IF (STATUS/=0) RETURN
 IF (C%VP(I)==0.AND.SUM(PM(:,I))>0) RETURN
 C%T(I)=T0(I);C%ENERGY(I)=CONTENT(SM(:,I),US,T0(I))+CONTENT(PM(:,I),C%UG,T0(I));C%P(I)=0
 IF (C%VP(I)>0) C%P(I)=SUM(PM(:,I)*RG)*T0(I)/C%VP(I)
ENDDO
C%READY=.TRUE.;B=C;IERR=0
END SUBROUTINE
SUBROUTINE ADVANCE_BODY(B,DT,HEAT,IERR)
TYPE(RETAINED_BODY),INTENT(INOUT) :: B
REAL(EB),INTENT(IN) :: DT,HEAT(:)
INTEGER,INTENT(OUT) :: IERR
TYPE(RETAINED_BODY) :: C
REAL(EB),ALLOCATABLE :: SMOLD(:,:),BORN_SOLID(:,:),BORN_GAS(:,:),MIXTAB(:,:),MIXMASS(:),NEWGAS(:,:), &
 ENEW(:),TNEW(:),PNEW(:),PORTS(:,:),GREL(:),PP(:),PT(:),PY(:,:),MASS_BEFORE(:),NATIVE_REF(:)
INTEGER,ALLOCATABLE :: ACTIVE(:),INDEX_OF(:),L(:),R(:),PORT_IDS(:),PORT_INDEX(:)
REAL(EB) :: LOSS(EAE_MAX_NODES),SURVIVOR(EAE_MAX_NODES),HAZARD(EAE_MAX_NODES),OLD_M,REQ,SCALE,ACTUAL,HREACTION,RES,M0,E0,M1,E1
INTEGER :: NM,NS,NC,NT,I,M,J,N,NN,STATUS,NA,NE,NP,STEPS,K,PORT
IERR=1
IF (.NOT.B%READY.OR..NOT.IEEE_IS_FINITE(DT).OR.DT<=0.OR.SIZE(HEAT)/=B%NC) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(HEAT)).OR..NOT.ALL(IEEE_IS_FINITE(B%CONDUCTANCE))) RETURN
IF (ANY(B%CONDUCTANCE<0)) RETURN
C=B;NM=C%NM;NS=C%NS;NC=C%NC;NT=C%NT
M0=SUM(C%SOLID)+SUM(C%PORE);E0=SUM(C%ENERGY)
ALLOCATE(SMOLD(NM,NC),BORN_SOLID(NM,NC),BORN_GAS(NS,NC),MIXTAB(0:NT,NM+NS),MIXMASS(NM+NS),INDEX_OF(NC),PORT_INDEX(C%NP))
SMOLD=C%SOLID;BORN_SOLID=0;BORN_GAS=0
! Consume all parent populations before depositing any newborn populations.
! This is first-order birth/depletion splitting, independent of MATL ordering.
DO I=1,NC
 DO M=1,NM
  IF (.NOT.C%KINETICS(M)%ENABLED) CYCLE
  NN=C%KINETICS(M)%NN;OLD_M=SUM(C%BINS(1:NN,M,I))
  CALL EAE_TRIAL(C%KINETICS(M),C%BINS(1:NN,M,I),C%T(I),DT,LOSS(1:NN))
  REQ=SUM(LOSS(1:NN));IF (REQ<=0) CYCLE
  SCALE=MIN(1._EB,C%CAP(M)*C%VM(I)*DT/REQ,OLD_M/REQ)
  IF (SCALE==1._EB) THEN
   ! Subtracting M*(1-exp(-H)) rounds a positive population to zero at
   ! H~37. That numerical cancellation must never authorize surface opening.
   HAZARD(1:NN)=MIN(700._EB,C%KINETICS(M)%A*EXP(-C%KINETICS(M)%ENERGY/(8.314462618_EB*MAX(C%T(I),1._EB)))*DT)
   SURVIVOR(1:NN)=C%BINS(1:NN,M,I)*EXP(-HAZARD(1:NN))
  ELSE
   SURVIVOR(1:NN)=C%BINS(1:NN,M,I)-SCALE*LOSS(1:NN)
  ENDIF
  IERR=7
  ! Reject representational exhaustion; never reinterpret it as physical burnout.
  IF (ANY(C%BINS(1:NN,M,I)>0.AND.SURVIVOR(1:NN)<=0)) RETURN
  C%BINS(1:NN,M,I)=SURVIVOR(1:NN)
  ACTUAL=OLD_M-SUM(C%BINS(1:NN,M,I));C%CONSUMED(M,I)=C%CONSUMED(M,I)+ACTUAL
  BORN_SOLID(:,I)=BORN_SOLID(:,I)+C%YS(:,M)*ACTUAL;BORN_GAS(:,I)=BORN_GAS(:,I)+C%YG(:,M)*ACTUAL
  ! Reference-pressure reaction enthalpy is diagnostic; chemical energy is
  ! already in the absolute property tables and is not added a second time.
  HREACTION=CONTENT(C%YG(:,M),C%HG,C%T(I))+CONTENT(C%YS(:,M),C%US,C%T(I))+ &
      C%PREF*SUM(C%YS(:,M)/C%RHO)-CONTENT([1._EB],C%US(:,M:M),C%T(I))-C%PREF/C%RHO(M)
  C%REFERENCE_HEAT(M,I)=C%REFERENCE_HEAT(M,I)-ACTUAL*HREACTION
 ENDDO
ENDDO
C%BORN_REF=C%BORN_REF+BORN_SOLID
DO I=1,NC
 DO M=1,NM
  IF (C%KINETICS(M)%ENABLED) THEN
   NN=C%KINETICS(M)%NN
   C%BINS(1:NN,M,I)=C%BINS(1:NN,M,I)+BORN_SOLID(M,I)*C%KINETICS(M)%WEIGHT
   C%SOLID(M,I)=SUM(C%BINS(1:NN,M,I))
  ELSE
   C%SOLID(M,I)=SMOLD(M,I)+BORN_SOLID(M,I)
  ENDIF
 ENDDO
 C%PORE(:,I)=C%PORE(:,I)+BORN_GAS(:,I);C%GENERATED(:,I)=C%GENERATED(:,I)+BORN_GAS(:,I)
 CALL MATRIX_POROSITY(C%SOLID(:,I),C%RHO,C%VM(I),C%VP(I),C%PHI(I),STATUS)
 IERR=2;IF (STATUS/=0) RETURN
 IF (C%VP(I)==0.AND.SUM(C%PORE(:,I))>0) RETURN
 C%ENERGY(I)=C%ENERGY(I)+HEAT(I)
 MIXTAB(:,1:NM)=C%US;MIXTAB(:,NM+1:)=C%UG;MIXMASS(1:NM)=C%SOLID(:,I);MIXMASS(NM+1:)=C%PORE(:,I)
 IF (SUM(MIXMASS)==0.AND.C%ENERGY(I)==0) THEN
  C%P(I)=0
 ELSE
  CALL MIXTURE_TEMPERATURE(MIXMASS,MIXTAB,C%ENERGY(I),C%T(I),RES,STATUS)
  IERR=3;IF (STATUS/=0) RETURN
  C%P(I)=0
  IF (C%VP(I)>0) C%P(I)=SUM(C%PORE(:,I)*C%RG)*C%T(I)/C%VP(I)
 ENDIF
ENDDO
NA=COUNT(C%VP>0);ALLOCATE(ACTIVE(NA));ACTIVE=PACK([(I,I=1,NC)],C%VP>0);INDEX_OF=0
DO I=1,NA;INDEX_OF(ACTIVE(I))=I;ENDDO
! Explicitly open interfaces to nonexistent pore volumes are contradictory data.
IERR=4
DO I=1,SIZE(C%LEFT)
 IF (C%CONDUCTANCE(I)<=0) CYCLE
 IF (INDEX_OF(C%LEFT(I))==0) RETURN
 IF (C%RIGHT(I)>0) THEN
  IF (INDEX_OF(C%RIGHT(I))==0) RETURN
 ENDIF
ENDDO
IF (NA>0) THEN
 NE=COUNT(C%CONDUCTANCE>0);PORT_INDEX=0;NP=0
 DO I=1,SIZE(C%LEFT)
  IF (C%CONDUCTANCE(I)<=0.OR.C%RIGHT(I)>0) CYCLE
  PORT=-C%RIGHT(I)
  IF (PORT_INDEX(PORT)==0) THEN
   NP=NP+1;PORT_INDEX(PORT)=NP
  ENDIF
 ENDDO
 ALLOCATE(L(NE),R(NE),GREL(NE),PORT_IDS(NP),PP(NP),PT(NP),PY(NS,NP), &
   NEWGAS(NS,NA),ENEW(NA),TNEW(NA),PNEW(NA),PORTS(NS+1,NP))
 DO I=1,C%NP
  IF (PORT_INDEX(I)==0) CYCLE
  J=PORT_INDEX(I);PORT_IDS(J)=I;PP(J)=C%PORT_P(I);PT(J)=C%PORT_T(I);PY(:,J)=C%PORT_Y(:,I)
 ENDDO
 K=0
 DO I=1,SIZE(C%LEFT)
  IF (C%CONDUCTANCE(I)<=0) CYCLE
  K=K+1;L(K)=INDEX_OF(C%LEFT(I));GREL(K)=C%CONDUCTANCE(I)
  IF (C%RIGHT(I)>0) THEN
   R(K)=INDEX_OF(C%RIGHT(I))
  ELSE
   R(K)=-PORT_INDEX(-C%RIGHT(I))
  ENDIF
 ENDDO
 CALL EQUILIBRATE_PORE_NETWORK(C%SOLID(:,ACTIVE),C%PORE(:,ACTIVE),C%ENERGY(ACTIVE),C%VP(ACTIVE), &
   C%US,C%HG,C%RG,L,R,GREL,PP,PT,PY,NEWGAS,ENEW,TNEW,PNEW,PORTS,STEPS,STATUS)
 IERR=5;IF (STATUS/=0) RETURN
 C%PORE(:,ACTIVE)=NEWGAS;C%ENERGY(ACTIVE)=ENEW;C%T(ACTIVE)=TNEW;C%P(ACTIVE)=PNEW
 DO I=1,NP;C%PORT_LEDGER(:,PORT_IDS(I))=C%PORT_LEDGER(:,PORT_IDS(I))+PORTS(:,I);ENDDO
ENDIF
IERR=6
M1=SUM(C%SOLID)+SUM(C%PORE)+SUM(C%PORT_LEDGER(1:NS,:)-B%PORT_LEDGER(1:NS,:))
E1=SUM(C%ENERGY)+SUM(C%PORT_LEDGER(NS+1,:)-B%PORT_LEDGER(NS+1,:))
IF (ABS(M1-M0)>1.E-10_EB*MAX(M0,TINY(1._EB))) RETURN
IF (ABS(E1-E0-SUM(HEAT))>1.E-10_EB*MAX(1._EB,ABS(E0),ABS(E1),SUM(ABS(HEAT)))) RETURN
DO I=1,NC;DO M=1,NM
 IF (.NOT.C%KINETICS(M)%ENABLED) CYCLE
 IF (ABS(SUM(C%BINS(:,M,I))+C%CONSUMED(M,I)-C%INITIAL_REF(M,I)-C%BORN_REF(M,I))> &
   1.E-10_EB*MAX(C%INITIAL_REF(M,I)+C%BORN_REF(M,I),TINY(1._EB))) RETURN
ENDDO;ENDDO
C%TIME=C%TIME+DT;B=C;IERR=0
END SUBROUTINE
END MODULE
