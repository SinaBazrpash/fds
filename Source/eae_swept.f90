! Conservative space-time fluid balance for Cartesian ablation cut volumes.
! No ambient initialization and no threshold-driven gas production.
MODULE EAE_SWEPT_VOLUME
USE PRECISION_PARAMETERS, ONLY: EB
USE EAE_CONSERVATIVE_REMAP, ONLY: MIXTURE_TEMPERATURE
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
IMPLICIT NONE
PRIVATE
PUBLIC :: SWEPT_FLUID_STEP, RECOVER_GAS_STATE
CONTAINS
SUBROUTINE SWEPT_FLUID_STEP(V0,V1,SWEEP_DV,Q0,LEFT,RIGHT,FLUX,PHASE_MASS,PHASE_H,PHASE_HEAT,P_WORK,Q1,EXCHANGE,IERR)
! Q species rows are kg; the last row is gas internal energy J (signed absolute
! reference permitted). FLUX is the already time-integrated physical flux across
! fixed Cartesian faces, positive LEFT -> RIGHT, and includes enthalpy/heat in
! its last row. Index 0 denotes the exterior, never a fictitious ambient donor.
! PHASE_MASS is accepted physical reaction yield, not an Eulerian volume fill.
! Interface energy: mass enthalpy + transferred heat - integral(p*w.n_g*dA*dt).
! Geometry conservation: V1-V0 = SWEEP_DV. All input/output state is extensive.
! Q1 and EXCHANGE are transactional: unchanged on every rejected update.
REAL(EB),INTENT(IN) :: V0(:),V1(:),SWEEP_DV(:),Q0(:,:),FLUX(:,:),PHASE_MASS(:,:),PHASE_H(:),PHASE_HEAT(:),P_WORK(:)
INTEGER,INTENT(IN) :: LEFT(:),RIGHT(:)
REAL(EB),INTENT(INOUT) :: Q1(:,:),EXCHANGE(:)
INTEGER,INTENT(OUT) :: IERR
REAL(EB),ALLOCATABLE :: TRIAL(:,:),CHANGE(:)
REAL(EB) :: SCALE
INTEGER :: N,NS,F,I
N=SIZE(V0);NS=SIZE(Q0,1)-1;IERR=1
IF (NS<1.OR.SIZE(V1)/=N.OR.SIZE(SWEEP_DV)/=N.OR.SIZE(Q0,2)/=N) RETURN
IF (ANY(SHAPE(Q1)/=SHAPE(Q0)).OR.SIZE(EXCHANGE)/=NS+1) RETURN
IF (SIZE(PHASE_MASS,1)/=NS.OR.SIZE(PHASE_MASS,2)/=N) RETURN
IF (SIZE(PHASE_H)/=N.OR.SIZE(PHASE_HEAT)/=N.OR.SIZE(P_WORK)/=N) RETURN
IF (SIZE(LEFT)/=SIZE(RIGHT).OR.SIZE(FLUX,2)/=SIZE(LEFT).OR.SIZE(FLUX,1)/=NS+1) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(V0)).OR..NOT.ALL(IEEE_IS_FINITE(V1)).OR..NOT.ALL(IEEE_IS_FINITE(SWEEP_DV))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(Q0)).OR..NOT.ALL(IEEE_IS_FINITE(FLUX)).OR..NOT.ALL(IEEE_IS_FINITE(PHASE_MASS))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(PHASE_H)).OR..NOT.ALL(IEEE_IS_FINITE(PHASE_HEAT)).OR..NOT.ALL(IEEE_IS_FINITE(P_WORK))) RETURN
IERR=2
IF (ANY(V0<0._EB).OR.ANY(V1<V0).OR.ANY(SWEEP_DV<0._EB)) RETURN
IF (ANY(Q0(1:NS,:)<0._EB).OR.ANY(PHASE_MASS<0._EB)) RETURN
DO I=1,N
 SCALE=MAX(V0(I),V1(I),SWEEP_DV(I),TINY(1._EB))
 IF (ABS(V1(I)-V0(I)-SWEEP_DV(I))>32._EB*EPSILON(1._EB)*SCALE) RETURN
 IF (V0(I)==0._EB.AND.ANY(Q0(:,I)/=0._EB)) RETURN
ENDDO
IERR=3
IF (ANY(LEFT<0).OR.ANY(LEFT>N).OR.ANY(RIGHT<0).OR.ANY(RIGHT>N)) RETURN
IF (ANY(LEFT==RIGHT)) RETURN
ALLOCATE(TRIAL(NS+1,N),CHANGE(NS+1));TRIAL=Q0
TRIAL(1:NS,:)=TRIAL(1:NS,:)+PHASE_MASS
TRIAL(NS+1,:)=TRIAL(NS+1,:)+PHASE_H+PHASE_HEAT-P_WORK
CHANGE(1:NS)=SUM(PHASE_MASS,DIM=2)
CHANGE(NS+1)=SUM(PHASE_H+PHASE_HEAT-P_WORK)
DO F=1,SIZE(LEFT)
 IF (LEFT(F)>0) TRIAL(:,LEFT(F))=TRIAL(:,LEFT(F))-FLUX(:,F)
 IF (RIGHT(F)>0) TRIAL(:,RIGHT(F))=TRIAL(:,RIGHT(F))+FLUX(:,F)
 IF (LEFT(F)==0) CHANGE=CHANGE+FLUX(:,F)
 IF (RIGHT(F)==0) CHANGE=CHANGE-FLUX(:,F)
ENDDO
IERR=4
IF (.NOT.ALL(IEEE_IS_FINITE(TRIAL)).OR..NOT.ALL(IEEE_IS_FINITE(CHANGE))) RETURN
! Never clip a negative population, invent a new-cell fill, or discard a vacuum.
IERR=5
IF (ANY(TRIAL(1:NS,:)<0._EB)) RETURN
DO I=1,N
 IERR=6
 IF (V1(I)>0._EB.AND.SUM(TRIAL(1:NS,I))<=0._EB) RETURN
 IERR=7
 IF (V1(I)==0._EB.AND.ANY(TRIAL(:,I)/=0._EB)) RETURN
ENDDO
Q1=TRIAL;EXCHANGE=CHANGE;IERR=0
END SUBROUTINE
SUBROUTINE RECOVER_GAS_STATE(MASS,INTERNAL_ENERGY,VOLUME,U_TABLE,R_SPEC,TEMPERATURE,PRESSURE,DENSITY,ZZ,RESIDUAL,IERR)
! Thermodynamic recovery from the conserved state, not from ambient/PBAR.
! Native low-Mach integration must enforce its pressure constraint through a
! conservative projection; replacing T by PBAR/(rho*R) would change energy.
REAL(EB),INTENT(IN) :: MASS(:),INTERNAL_ENERGY,VOLUME,U_TABLE(0:,:),R_SPEC(:)
REAL(EB),INTENT(INOUT) :: TEMPERATURE,PRESSURE,DENSITY,ZZ(:),RESIDUAL
INTEGER,INTENT(OUT) :: IERR
REAL(EB) :: T,P,RHO,RES,MTOT
IERR=1
IF (SIZE(R_SPEC)/=SIZE(MASS).OR.SIZE(ZZ)/=SIZE(MASS)) RETURN
IF (.NOT.IEEE_IS_FINITE(VOLUME).OR.VOLUME<=0._EB) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(R_SPEC)).OR.ANY(R_SPEC<=0._EB)) RETURN
CALL MIXTURE_TEMPERATURE(MASS,U_TABLE,INTERNAL_ENERGY,T,RES,IERR)
IF (IERR/=0) RETURN
IERR=8;MTOT=SUM(MASS)
RHO=MTOT/VOLUME;P=SUM(MASS*R_SPEC)*T/VOLUME
IF (.NOT.ALL(IEEE_IS_FINITE([T,P,RHO,RES])).OR.MIN(T,P,RHO)<=0._EB) RETURN
TEMPERATURE=T;PRESSURE=P;DENSITY=RHO;ZZ=MASS/MTOT;RESIDUAL=RES;IERR=0
END SUBROUTINE
END MODULE
