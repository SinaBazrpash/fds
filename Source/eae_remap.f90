! Conservative state transfer for prescribed Cartesian front/reconstruction geometry.
! Every field is EXTENSIVE: kg bins/materials/references/history, J enthalpy/heat.
! This module supplies no recession law and never converts omitted material to gas.
MODULE EAE_CONSERVATIVE_REMAP
USE PRECISION_PARAMETERS, ONLY: EB
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
IMPLICIT NONE
PRIVATE
PUBLIC :: CARTESIAN_REMAP, APPLY_TRANSFER, MIXTURE_TEMPERATURE, AGGLOMERATE_EXTENSIVE
CONTAINS
PURE REAL(EB) FUNCTION VOLUME(B) RESULT(V)
REAL(EB),INTENT(IN) :: B(6)
V=(B(2)-B(1))*(B(4)-B(3))*(B(6)-B(5))
END FUNCTION
PURE REAL(EB) FUNCTION OVERLAP(A,B) RESULT(V)
REAL(EB),INTENT(IN) :: A(6),B(6)
V=MAX(0._EB,MIN(A(2),B(2))-MAX(A(1),B(1)))* &
  MAX(0._EB,MIN(A(4),B(4))-MAX(A(3),B(3)))* &
  MAX(0._EB,MIN(A(6),B(6))-MAX(A(5),B(5)))
END FUNCTION
SUBROUTINE CARTESIAN_REMAP(OLD_BOX,NEW_BOX,OLD_Q,NEW_Q,UNMAPPED_Q,IERR)
REAL(EB),INTENT(IN) :: OLD_BOX(:,:),NEW_BOX(:,:),OLD_Q(:,:)
REAL(EB),INTENT(OUT) :: NEW_Q(:,:),UNMAPPED_Q(:,:)
INTEGER,INTENT(OUT) :: IERR
REAL(EB),ALLOCATABLE :: W(:,:),VO(:),VN(:)
INTEGER :: I,J,NO,NN
REAL(EB),PARAMETER :: GEOMETRY_ROUNDOFF=32._EB*EPSILON(1._EB)
IERR=1;NEW_Q=0;UNMAPPED_Q=0
NO=SIZE(OLD_BOX,2);NN=SIZE(NEW_BOX,2)
IF (SIZE(OLD_BOX,1)/=6.OR.SIZE(NEW_BOX,1)/=6.OR.SIZE(OLD_Q,2)/=NO) RETURN
IF (SIZE(NEW_Q,1)/=SIZE(OLD_Q,1).OR.SIZE(NEW_Q,2)/=NN) RETURN
IF (ANY(SHAPE(UNMAPPED_Q)/=SHAPE(OLD_Q))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(OLD_BOX)).OR..NOT.ALL(IEEE_IS_FINITE(NEW_BOX))) RETURN
ALLOCATE(VO(NO),VN(NN),W(NN,NO));W=0
DO I=1,NO
 IF (ANY(OLD_BOX([2,4,6],I)<=OLD_BOX([1,3,5],I))) RETURN
 VO(I)=VOLUME(OLD_BOX(:,I));IF (.NOT.IEEE_IS_FINITE(VO(I)).OR.VO(I)<=0) RETURN
ENDDO
DO J=1,NN
 IF (ANY(NEW_BOX([2,4,6],J)<=NEW_BOX([1,3,5],J))) RETURN
 VN(J)=VOLUME(NEW_BOX(:,J));IF (.NOT.IEEE_IS_FINITE(VN(J)).OR.VN(J)<=0) RETURN
ENDDO
! Neither input tessellation may count the same physical volume twice.
IERR=2
DO I=1,NO;DO J=I+1,NO
 IF (OVERLAP(OLD_BOX(:,I),OLD_BOX(:,J))>GEOMETRY_ROUNDOFF*MIN(VO(I),VO(J))) RETURN
ENDDO;ENDDO
DO I=1,NN;DO J=I+1,NN
 IF (OVERLAP(NEW_BOX(:,I),NEW_BOX(:,J))>GEOMETRY_ROUNDOFF*MIN(VN(I),VN(J))) RETURN
ENDDO;ENDDO
DO I=1,NO;DO J=1,NN
 W(J,I)=OVERLAP(NEW_BOX(:,J),OLD_BOX(:,I))/VO(I)
ENDDO;ENDDO
CALL APPLY_TRANSFER(W,OLD_Q,NEW_Q,UNMAPPED_Q,IERR)
END SUBROUTINE
SUBROUTINE APPLY_TRANSFER(W,OLD_Q,NEW_Q,UNMAPPED_Q,IERR)
! Supports geometric overlap, conservative cell merging and explicit ownership
! redistribution. Caller supplies physical transfer fractions, never intensities.
REAL(EB),INTENT(IN) :: W(:,:),OLD_Q(:,:)
REAL(EB),INTENT(OUT) :: NEW_Q(:,:),UNMAPPED_Q(:,:)
INTEGER,INTENT(OUT) :: IERR
INTEGER :: I,J
REAL(EB) :: COVER
IERR=1;NEW_Q=0;UNMAPPED_Q=0
IF (SIZE(W,2)/=SIZE(OLD_Q,2).OR.SIZE(W,1)/=SIZE(NEW_Q,2)) RETURN
IF (SIZE(NEW_Q,1)/=SIZE(OLD_Q,1).OR.ANY(SHAPE(UNMAPPED_Q)/=SHAPE(OLD_Q))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(W)).OR..NOT.ALL(IEEE_IS_FINITE(OLD_Q))) RETURN
IF (ANY(W<0._EB)) RETURN
! No column normalization: uncovered state is an explicit per-source return.
DO I=1,SIZE(W,2)
 COVER=SUM(W(:,I))
 IERR=3
 IF (.NOT.IEEE_IS_FINITE(COVER).OR.COVER>1._EB+32._EB*EPSILON(1._EB)) RETURN
 DO J=1,SIZE(W,1)
  NEW_Q(:,J)=NEW_Q(:,J)+W(J,I)*OLD_Q(:,I)
 ENDDO
 UNMAPPED_Q(:,I)=MAX(0._EB,1._EB-COVER)*OLD_Q(:,I)
ENDDO
IERR=4
IF (.NOT.ALL(IEEE_IS_FINITE(NEW_Q)).OR..NOT.ALL(IEEE_IS_FINITE(UNMAPPED_Q))) RETURN
IERR=0
END SUBROUTINE
SUBROUTINE AGGLOMERATE_EXTENSIVE(PARENT,OLD_Q,NEW_Q,IERR)
! Sparse one-target conservative transfer. No deletion destination is allowed.
INTEGER,INTENT(IN) :: PARENT(:)
REAL(EB),INTENT(IN) :: OLD_Q(:,:)
REAL(EB),INTENT(OUT) :: NEW_Q(:,:)
INTEGER,INTENT(OUT) :: IERR
INTEGER :: I,N
IERR=1;NEW_Q=0;N=SIZE(PARENT)
IF (ANY(SHAPE(NEW_Q)/=SHAPE(OLD_Q)).OR.SIZE(OLD_Q,2)/=N) RETURN
IF (ANY(PARENT<1).OR.ANY(PARENT>N)) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(OLD_Q))) RETURN
DO I=1,N
 IF (PARENT(PARENT(I))/=PARENT(I)) RETURN
ENDDO
DO I=1,N
 NEW_Q(:,PARENT(I))=NEW_Q(:,PARENT(I))+OLD_Q(:,I)
ENDDO
IERR=4
IF (.NOT.ALL(IEEE_IS_FINITE(NEW_Q))) RETURN
IERR=0
END SUBROUTINE
SUBROUTINE MIXTURE_TEMPERATURE(MASS,H,TOTAL_H,TEMPERATURE,RESIDUAL,IERR)
! H(0:NT,material) is native tabulated material-specific sensible enthalpy J/kg.
! Invert total extensive J, not temperature averages; includes mixed materials.
REAL(EB),INTENT(IN) :: MASS(:),H(0:,:),TOTAL_H
REAL(EB),INTENT(OUT) :: TEMPERATURE,RESIDUAL
INTEGER,INTENT(OUT) :: IERR
INTEGER :: LO,HI,MID,NT,I
REAL(EB) :: HL,HH,HM,TARGET,HTOL
IERR=1;TEMPERATURE=0;RESIDUAL=TOTAL_H
NT=UBOUND(H,1)
IF (SIZE(H,2)/=SIZE(MASS).OR.NT<1) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(MASS)).OR..NOT.ALL(IEEE_IS_FINITE(H)).OR..NOT.IEEE_IS_FINITE(TOTAL_H)) RETURN
IF (ANY(MASS<0).OR.SUM(MASS)<=0) RETURN
DO I=1,NT
 IF (SUM(MASS*(H(I,:)-H(I-1,:)))<=0) RETURN
ENDDO
LO=0;HI=NT;HL=SUM(MASS*H(LO,:));HH=SUM(MASS*H(HI,:))
HTOL=16._EB*EPSILON(1._EB)*MAX(1._EB,ABS(HL),ABS(HH),ABS(TOTAL_H))
IERR=5
IF (TOTAL_H<HL-HTOL.OR.TOTAL_H>HH+HTOL) RETURN
TARGET=MIN(HH,MAX(HL,TOTAL_H))
DO WHILE (HI-LO>1)
 MID=(LO+HI)/2;HM=SUM(MASS*H(MID,:))
 IF (HM>TARGET) THEN
  HI=MID
 ELSE
  LO=MID
 ENDIF
ENDDO
HL=SUM(MASS*H(LO,:));HH=SUM(MASS*H(HI,:))
TEMPERATURE=REAL(LO,EB)+(TARGET-HL)/(HH-HL)
RESIDUAL=TOTAL_H-(HL+(TEMPERATURE-LO)*(HH-HL))
IERR=0
END SUBROUTINE
END MODULE
