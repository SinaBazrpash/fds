! Retained-matrix porosity and a local LTE pore control-volume update.
! Connectivity is supplied explicitly, not inferred from porosity.
! Absolute solid internal-energy and gas enthalpy tables must share a consistent
! thermochemical reference. Reaction heat is encoded by composition changes in
! those tables and MUST NOT also be added as an explicit thermal source.
MODULE EAE_PORE_LTE
USE PRECISION_PARAMETERS,ONLY: EB
USE EAE_CONSERVATIVE_REMAP,ONLY: MIXTURE_TEMPERATURE
USE,INTRINSIC :: IEEE_ARITHMETIC,ONLY: IEEE_IS_FINITE
IMPLICIT NONE
PRIVATE
PUBLIC :: MATRIX_POROSITY, PORE_COMPONENTS, LTE_PORE_CELL, OPEN_DEPLETED_CELL
CONTAINS
SUBROUTINE MATRIX_POROSITY(MASS,RHO,MATRIX_VOLUME,PORE_VOLUME,POROSITY,IERR)
REAL(EB),INTENT(IN) :: MASS(:),RHO(:),MATRIX_VOLUME
REAL(EB),INTENT(INOUT) :: PORE_VOLUME,POROSITY
INTEGER,INTENT(OUT) :: IERR
REAL(EB) :: OCCUPIED
IERR=1
IF (SIZE(MASS)/=SIZE(RHO).OR..NOT.IEEE_IS_FINITE(MATRIX_VOLUME).OR.MATRIX_VOLUME<=0) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(MASS)).OR..NOT.ALL(IEEE_IS_FINITE(RHO))) RETURN
IF (ANY(MASS<0).OR.ANY(RHO<=0)) RETURN
OCCUPIED=SUM(MASS/RHO)
IERR=2
IF (.NOT.IEEE_IS_FINITE(OCCUPIED).OR.OCCUPIED>MATRIX_VOLUME*(1+32*EPSILON(1._EB))) RETURN
PORE_VOLUME=MAX(0._EB,MATRIX_VOLUME-OCCUPIED);POROSITY=PORE_VOLUME/MATRIX_VOLUME;IERR=0
END SUBROUTINE
SUBROUTINE PORE_COMPONENTS(VP,LEFT,RIGHT,OPEN_AREA,LABEL,VENTED,IERR)
! Positive OPEN_AREA must be a verified open pore interface, NOT merely a
! solid-grid face with positive adjacent porosities. RIGHT=0 is an exposed port.
REAL(EB),INTENT(IN) :: VP(:),OPEN_AREA(:)
INTEGER,INTENT(IN) :: LEFT(:),RIGHT(:)
INTEGER,INTENT(INOUT) :: LABEL(:)
LOGICAL,INTENT(INOUT) :: VENTED(:)
INTEGER,INTENT(OUT) :: IERR
INTEGER,ALLOCATABLE :: P(:)
LOGICAL,ALLOCATABLE :: V(:)
INTEGER :: N,I,A,B,J,K
N=SIZE(VP);IERR=1
IF (SIZE(LABEL)/=N.OR.SIZE(VENTED)/=N.OR.SIZE(LEFT)/=SIZE(RIGHT).OR.SIZE(OPEN_AREA)/=SIZE(LEFT)) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(VP)).OR..NOT.ALL(IEEE_IS_FINITE(OPEN_AREA))) RETURN
IF (ANY(VP<0).OR.ANY(OPEN_AREA<0).OR.ANY(LEFT<1).OR.ANY(LEFT>N).OR.ANY(RIGHT<0).OR.ANY(RIGHT>N)) RETURN
IF (ANY(LEFT==RIGHT)) RETURN
ALLOCATE(P(N),V(N));P=[(I,I=1,N)];V=.FALSE.
DO I=1,SIZE(LEFT)
 A=LEFT(I);B=RIGHT(I)
 IF (OPEN_AREA(I)==0.OR.VP(A)==0.OR.B==0) CYCLE
 IF (VP(B)==0) CYCLE
 DO WHILE(P(A)/=A);A=P(A);ENDDO
 DO WHILE(P(B)/=B);B=P(B);ENDDO
 P(MAX(A,B))=MIN(A,B)
ENDDO
DO I=1,N
 J=I
 DO WHILE(P(J)/=J);J=P(J);ENDDO
 P(I)=J
ENDDO
DO I=1,SIZE(LEFT)
 IF (RIGHT(I)/=0.OR.OPEN_AREA(I)<=0) CYCLE
 J=LEFT(I)
 IF (VP(J)>0) V(P(J))=.TRUE.
ENDDO
DO I=1,N
 IF (VP(I)>0) THEN
  LABEL(I)=P(I);VENTED(I)=V(P(I))
 ELSE
  LABEL(I)=0;VENTED(I)=.FALSE.
 ENDIF
ENDDO
IERR=0
END SUBROUTINE
SUBROUTINE OPEN_DEPLETED_CELL(SOLID_MASS,BINS,REACTIVE,EXPOSED,VMATRIX,VPORE,R,UG,PEXT, &
 PORE_MASS,PORE_U,HISTORY,FLUID_Q,ARCHIVE,IERR)
REAL(EB),INTENT(IN) :: SOLID_MASS(:),BINS(:,:),VMATRIX,R(:),UG(0:,:),PEXT
LOGICAL,INTENT(IN) :: REACTIVE(:),EXPOSED
REAL(EB),INTENT(INOUT) :: VPORE,PORE_MASS(:),PORE_U,HISTORY(:),FLUID_Q(:),ARCHIVE(:)
INTEGER,INTENT(OUT) :: IERR
INTEGER :: M,STATUS
REAL(EB) :: T,RES,P
IERR=1
IF (SIZE(BINS,2)/=SIZE(SOLID_MASS).OR.SIZE(REACTIVE)/=SIZE(SOLID_MASS)) RETURN
IF (SIZE(FLUID_Q)/=SIZE(PORE_MASS)+1.OR.SIZE(ARCHIVE)/=SIZE(HISTORY).OR.SIZE(R)/=SIZE(PORE_MASS)) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(SOLID_MASS)).OR..NOT.ALL(IEEE_IS_FINITE(BINS))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE([VMATRIX,VPORE,PORE_U,PEXT])).OR..NOT.ALL(IEEE_IS_FINITE(PORE_MASS))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(HISTORY)).OR..NOT.ALL(IEEE_IS_FINITE(ARCHIVE)).OR..NOT.ALL(IEEE_IS_FINITE(FLUID_Q))) RETURN
IF (ANY(SOLID_MASS<0).OR.ANY(BINS<0).OR.ANY(PORE_MASS<0).OR.VMATRIX<=0.OR.PEXT<=0) RETURN
DO M=1,SIZE(SOLID_MASS)
 IF (REACTIVE(M)) THEN
  IF (ABS(SUM(BINS(:,M))-SOLID_MASS(M))>1.E-10_EB*MAX(SOLID_MASS(M),SUM(BINS(:,M)),TINY(1._EB))) RETURN
 ELSE
  IF (ANY(BINS(:,M)/=0._EB)) RETURN
 ENDIF
ENDDO
! Physical conversion, not a minimum-layer threshold or small-mass cutoff.
IERR=2
IF (.NOT.EXPOSED.OR.ANY(SOLID_MASS/=0._EB).OR.ANY(BINS/=0._EB)) RETURN
IERR=3
IF (ABS(VPORE-VMATRIX)>32*EPSILON(1._EB)*VMATRIX.OR.ANY(FLUID_Q/=0._EB)) RETURN
! A vacuum cannot be assigned an ambient fill. Equilibrate conservatively via
! a real exposed pore port before switching to the native low-Mach fluid path.
IERR=4
IF (SUM(PORE_MASS)<=0._EB.OR.ANY(R<=0).OR..NOT.ALL(IEEE_IS_FINITE(R))) RETURN
CALL MIXTURE_TEMPERATURE(PORE_MASS,UG,PORE_U,T,RES,STATUS)
IF (STATUS/=0) RETURN
P=SUM(PORE_MASS*R)*T/VPORE
IF (.NOT.IEEE_IS_FINITE(P).OR.ABS(P-PEXT)>1.E-10_EB*PEXT) RETURN
FLUID_Q(1:SIZE(PORE_MASS))=PORE_MASS;FLUID_Q(SIZE(FLUID_Q))=PORE_U
ARCHIVE=ARCHIVE+HISTORY;HISTORY=0;PORE_MASS=0;PORE_U=0;VPORE=0;IERR=0
END SUBROUTINE
REAL(EB) FUNCTION TABLE_ENERGY(MASS,TABLE,T) RESULT(E)
REAL(EB),INTENT(IN) :: MASS(:),TABLE(0:,:),T
INTEGER :: IT
IT=MIN(UBOUND(TABLE,1)-1,MAX(0,INT(T)))
E=SUM(MASS*(TABLE(IT,:)+(T-IT)*(TABLE(IT+1,:)-TABLE(IT,:))))
END FUNCTION
SUBROUTINE LTE_PORE_CELL(SM0,SM1,PM0,BIRTH,VP0,VP1,US,HG,R,T0,QEXT,CONNECTED,PEXT,YEXT,TEXT, &
 PM1,T1,P1,M_TO_PORT,H_TO_PORT,ENERGY_RESIDUAL,IERR)
! One LOCAL finite-volume LTE cell. Interior network nodes exchange with their
! adjacent network, not directly with exterior fluid. A network solver must
! provide actual incoming composition/enthalpy and pressure constraints.
! Sealed: U_s(T1)+U_p(T1)=U_old+Qext; no exchange.
! Connected venting: U_s(T1)+sum(Mpre*h_g(T1))=U_old+Qext+Pext*Vp1.
! Connected inflow: U_new=U_old+Qext+Min*h_ext; enforce EOS at Pext.
! H_TO_PORT is signed enthalpy transport, positive OUT. No second p*dV term
! is added to this combined-phase, fixed-matrix control volume.
REAL(EB),INTENT(IN) :: SM0(:),SM1(:),PM0(:),BIRTH(:),VP0,VP1,US(0:,:),HG(0:,:),R(:),T0,QEXT,PEXT,YEXT(:),TEXT
LOGICAL,INTENT(IN) :: CONNECTED
REAL(EB),INTENT(INOUT) :: PM1(:),T1,P1,M_TO_PORT(:),H_TO_PORT,ENERGY_RESIDUAL
INTEGER,INTENT(OUT) :: IERR
REAL(EB),ALLOCATABLE :: UG(:,:),TAB(:,:),MPRE(:),MASS(:),MP(:),FLOW(:)
REAL(EB) :: E0,TARGET,T,RES,P,MT,MEQ,HPORT,HEXT,LO,HI,MID,PL,PH,ERR,EFINAL,RS
INTEGER :: NM,NG,NT,I,J,STATUS,ITER
IERR=1;NM=SIZE(SM0);NG=SIZE(PM0);NT=UBOUND(US,1)
IF (SIZE(SM1)/=NM.OR.SIZE(US,2)/=NM.OR.SIZE(HG,2)/=NG.OR.UBOUND(HG,1)/=NT.OR.NT<1) RETURN
IF (SIZE(BIRTH)/=NG.OR.SIZE(R)/=NG.OR.SIZE(YEXT)/=NG.OR.SIZE(PM1)/=NG.OR.SIZE(M_TO_PORT)/=NG) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(SM0)).OR..NOT.ALL(IEEE_IS_FINITE(SM1)).OR..NOT.ALL(IEEE_IS_FINITE(PM0))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(BIRTH)).OR..NOT.ALL(IEEE_IS_FINITE(US)).OR..NOT.ALL(IEEE_IS_FINITE(HG))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(R)).OR..NOT.ALL(IEEE_IS_FINITE([VP0,VP1,T0,QEXT]))) RETURN
IF (ANY(SM0<0).OR.ANY(SM1<0).OR.ANY(PM0<0).OR.ANY(BIRTH<0).OR.ANY(R<=0)) RETURN
IF (MIN(VP0,VP1)<0.OR.T0<=0.OR.T0>NT) RETURN
IF (VP0==0.AND.ANY(PM0/=0)) RETURN
! Every gas source must be an actual solid mass conversion, never a threshold.
! Connected pressure jumps require the validated network limiting path.
IERR=9
IF (CONNECTED) RETURN
IERR=2
ERR=SUM(SM0)-SUM(SM1)-SUM(BIRTH)
IF (ABS(ERR)>1.E-10_EB*MAX(SUM(SM0),SUM(SM1),SUM(BIRTH),TINY(1._EB))) RETURN
ALLOCATE(UG(0:NT,NG),TAB(0:NT,NM+NG),MASS(NM+NG),MPRE(NG),MP(NG),FLOW(NG))
DO I=0,NT
 UG(I,:)=HG(I,:)-R*REAL(I,EB)
ENDDO
MPRE=PM0+BIRTH;MT=SUM(MPRE)
E0=TABLE_ENERGY(SM0,US,T0)+TABLE_ENERGY(PM0,UG,T0)
TARGET=E0+QEXT;FLOW=0;HPORT=0;MASS(1:NM)=SM1
TAB(:,1:NM)=US
IF (.NOT.CONNECTED) THEN
 IERR=3
 IF (VP1==0.AND.MT>0) RETURN
 TAB(:,NM+1:)=UG;MASS(NM+1:)=MPRE
 IF (SUM(MASS)==0._EB.AND.TARGET==0._EB) THEN
  T=T0;RES=0;STATUS=0
 ELSE
  CALL MIXTURE_TEMPERATURE(MASS,TAB,TARGET,T,RES,STATUS)
 ENDIF
 IF (STATUS/=0) RETURN
 MP=MPRE;P=0
 IF (VP1>0) P=SUM(MP*R)*T/VP1
ELSE
 IERR=4
 IF (.NOT.ALL(IEEE_IS_FINITE([PEXT,TEXT])).OR.PEXT<=0.OR.TEXT<=0.OR.TEXT>NT) RETURN
 IF (.NOT.ALL(IEEE_IS_FINITE(YEXT)).OR.ANY(YEXT<0).OR.ABS(SUM(YEXT)-1._EB)>32*EPSILON(1._EB)) RETURN
 HEXT=TABLE_ENERGY(YEXT,HG,TEXT)
 TAB(:,NM+1:)=HG;MASS(NM+1:)=MPRE
 IF (SUM(MASS)==0._EB.AND.TARGET==0._EB.AND.VP1>0._EB) THEN
  ! Adiabatic filling of an initially empty rigid pore: u(Tfill)=h(inlet).
  ! For calorically perfect gas this gives Tfill=gamma*Text, not Text.
  CALL MIXTURE_TEMPERATURE(YEXT,UG,HEXT,T,RES,STATUS)
  IF (STATUS/=0) RETURN
  MP=YEXT*PEXT*VP1/(SUM(YEXT*R)*T)
  FLOW=-MP;HPORT=-SUM(MP)*HEXT;P=PEXT
 ELSE
 CALL MIXTURE_TEMPERATURE(MASS,TAB,TARGET+PEXT*VP1,T,RES,STATUS)
 IERR=5
 IF (STATUS/=0) RETURN
 IF (VP1==0) THEN
  MP=0;FLOW=MPRE;HPORT=TABLE_ENERGY(FLOW,HG,T);P=0
 ELSE
  MEQ=HUGE(1._EB)
  IF (MT>0) MEQ=PEXT*VP1/(SUM(MPRE*R)/MT*T)
  IF (MEQ<=MT) THEN
   MP=MPRE*(MEQ/MT);FLOW=MPRE-MP;HPORT=TABLE_ENERGY(FLOW,HG,T);P=SUM(MP*R)*T/VP1
  ELSE
   ! Pressure deficit: conservative inflow from the explicitly supplied port.
   TAB(:,NM+1:)=UG;MASS(NM+1:)=MPRE
   CALL MIXTURE_TEMPERATURE(MASS,TAB,TARGET,T,RES,STATUS)
   IF (STATUS/=0) RETURN
   LO=0;HI=MAX(MT,PEXT*VP1/(SUM(YEXT*R)*TEXT),TINY(1._EB));PH=0
   DO ITER=1,128
    CALL INFLOW_STATE(HI,T,PH,STATUS)
    IF (STATUS/=0) RETURN
    IF (PH>=PEXT) EXIT
    HI=HI*2
    IF (.NOT.IEEE_IS_FINITE(HI)) RETURN
   ENDDO
   IF (PH<PEXT) RETURN
   DO ITER=1,128
    MID=0.5_EB*(LO+HI);CALL INFLOW_STATE(MID,T,P,STATUS)
    IF (STATUS/=0) RETURN
    IF (P>PEXT) THEN
     HI=MID
    ELSE
     LO=MID
    ENDIF
    IF (HI-LO<=8*EPSILON(1._EB)*MAX(HI,TINY(1._EB))) EXIT
   ENDDO
   MID=0.5_EB*(LO+HI);CALL INFLOW_STATE(MID,T,P,STATUS)
   IF (STATUS/=0) RETURN
   MP=MPRE+MID*YEXT;FLOW=-MID*YEXT;HPORT=-MID*HEXT
  ENDIF
 ENDIF
ENDIF
ENDIF
IERR=6
IF (.NOT.ALL(IEEE_IS_FINITE([T,P,HPORT])).OR.T<=0.OR.ANY(MP<0)) RETURN
EFINAL=TABLE_ENERGY(SM1,US,T)+TABLE_ENERGY(MP,UG,T)
ERR=EFINAL+HPORT-TARGET
IF (ABS(ERR)>1.E-10_EB*MAX(1._EB,ABS(TARGET),ABS(EFINAL),ABS(HPORT))) RETURN
IF (CONNECTED.AND.VP1>0) THEN
 IF (ABS(P-PEXT)>1.E-10_EB*PEXT) RETURN
ENDIF
PM1=MP;T1=T;P1=P;M_TO_PORT=FLOW;H_TO_PORT=HPORT;ENERGY_RESIDUAL=ERR;IERR=0
CONTAINS
SUBROUTINE INFLOW_STATE(MINLET,TT,PP,STAT)
REAL(EB),INTENT(IN) :: MINLET
REAL(EB),INTENT(OUT) :: TT,PP
INTEGER,INTENT(OUT) :: STAT
REAL(EB) :: RR
MASS(NM+1:)=MPRE+MINLET*YEXT
CALL MIXTURE_TEMPERATURE(MASS,TAB,TARGET+MINLET*HEXT,TT,RR,STAT)
PP=0
IF (STAT==0) PP=SUM(MASS(NM+1:)*R)*TT/VP1
END SUBROUTINE
END SUBROUTINE
END MODULE
