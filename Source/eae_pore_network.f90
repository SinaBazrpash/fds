! Zero-resistance limit of an explicitly specified relative MASS-conductance
! network. Fast relaxation time is numerical only; no physical permeability
! or finite transport time is inferred. Every edge transfers upwind species
! and enthalpy conservatively; local LTE uses combined absolute internal energy.
MODULE EAE_PORE_NETWORK
USE PRECISION_PARAMETERS,ONLY: EB
USE EAE_CONSERVATIVE_REMAP,ONLY: MIXTURE_TEMPERATURE
USE,INTRINSIC :: IEEE_ARITHMETIC,ONLY: IEEE_IS_FINITE
IMPLICIT NONE
PRIVATE
PUBLIC :: EQUILIBRATE_PORE_NETWORK
CONTAINS
SUBROUTINE EQUILIBRATE_PORE_NETWORK(SM,GM0,E0,VP,US,HG,RG,LEFT,RIGHT,GREL,PORT_P,PORT_T,PORT_Y, &
 GM1,E1,T1,P1,PORT_TRANSFER,STEPS,IERR)
! RIGHT<0 denotes port -RIGHT; LEFT always denotes a local node. Zero conductance
! means a closed interface. Positive values must come from explicit pore data.
! Reject a component connected to unequal prescribed port pressures: its
! zero-resistance steady throughflow has no finite well-defined limit.
REAL(EB),INTENT(IN) :: SM(:,:),GM0(:,:),E0(:),VP(:),US(0:,:),HG(0:,:),RG(:),GREL(:),PORT_P(:),PORT_T(:),PORT_Y(:,:)
INTEGER,INTENT(IN) :: LEFT(:),RIGHT(:)
REAL(EB),INTENT(INOUT) :: GM1(:,:),E1(:),T1(:),P1(:),PORT_TRANSFER(:,:)
INTEGER,INTENT(OUT) :: STEPS,IERR
REAL(EB),ALLOCATABLE :: STATE(:,:),FULL(:,:),HALF(:,:),TRIAL(:,:),G(:),UG(:,:),TABLE(:,:),TEMP(:),PRES(:),SUMG(:),ANCHOR(:)
INTEGER,ALLOCATABLE :: ROOT(:)
INTEGER :: N,NS,NM,NP,NF,NT,I,J,A,B,K,STAT,REJECTS
REAL(EB) :: DT,DTMAX,SENS,ERR,SCALE,TREF,FACTOR
N=SIZE(VP);NS=SIZE(GM0,1);NM=SIZE(SM,1);NP=SIZE(PORT_P);NF=SIZE(LEFT);NT=UBOUND(US,1)
IERR=1;STEPS=0
IF (N<1.OR.NS<1.OR.NM<1.OR.NT<1.OR.SIZE(SM,2)/=N.OR.SIZE(GM0,2)/=N.OR.SIZE(E0)/=N) RETURN
IF (SIZE(US,2)/=NM.OR.SIZE(HG,2)/=NS.OR.UBOUND(HG,1)/=NT.OR.SIZE(RG)/=NS) RETURN
IF (SIZE(RIGHT)/=NF.OR.SIZE(GREL)/=NF.OR.SIZE(PORT_T)/=NP.OR.SIZE(PORT_Y,1)/=NS.OR.SIZE(PORT_Y,2)/=NP) RETURN
IF (ANY(SHAPE(GM1)/=SHAPE(GM0)).OR.SIZE(E1)/=N.OR.SIZE(T1)/=N.OR.SIZE(P1)/=N) RETURN
IF (SIZE(PORT_TRANSFER,1)/=NS+1.OR.SIZE(PORT_TRANSFER,2)/=NP) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(SM)).OR..NOT.ALL(IEEE_IS_FINITE(GM0)).OR..NOT.ALL(IEEE_IS_FINITE(E0))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(VP)).OR..NOT.ALL(IEEE_IS_FINITE(US)).OR..NOT.ALL(IEEE_IS_FINITE(HG))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(RG)).OR..NOT.ALL(IEEE_IS_FINITE(GREL))) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE(PORT_P)).OR..NOT.ALL(IEEE_IS_FINITE(PORT_T)).OR..NOT.ALL(IEEE_IS_FINITE(PORT_Y))) RETURN
IF (ANY(SM<0).OR.ANY(GM0<0).OR.ANY(VP<=0).OR.ANY(RG<=0).OR.ANY(GREL<0)) RETURN
IF (ANY(LEFT<1).OR.ANY(LEFT>N).OR.ANY(RIGHT==0).OR.ANY(RIGHT>N).OR.ANY(RIGHT< -NP).OR.ANY(LEFT==RIGHT)) RETURN
IF (ANY(PORT_P<=0).OR.ANY(PORT_T<=0).OR.ANY(PORT_T>NT).OR.ANY(PORT_Y<0)) RETURN
DO I=1,NP
 IF (ABS(SUM(PORT_Y(:,I))-1._EB)>32*EPSILON(1._EB)) RETURN
ENDDO
ALLOCATE(STATE(NS+1,N+NP),FULL(NS+1,N+NP),HALF(NS+1,N+NP),TRIAL(NS+1,N+NP), &
 G(NF),UG(0:NT,NS),TABLE(0:NT,NM+NS),TEMP(N),PRES(N),SUMG(N),ROOT(N),ANCHOR(N))
G=0
IF (NF>0) THEN
 IF (MAXVAL(GREL)>0) G=GREL/MAXVAL(GREL)
ENDIF
ROOT=[(I,I=1,N)];ANCHOR=0;SUMG=0
DO I=1,NF
 IF (G(I)==0) CYCLE
 A=LEFT(I);B=RIGHT(I);SUMG(A)=SUMG(A)+G(I)
 IF (B<0) CYCLE
 SUMG(B)=SUMG(B)+G(I)
 DO WHILE(ROOT(A)/=A);A=ROOT(A);ENDDO
 DO WHILE(ROOT(B)/=B);B=ROOT(B);ENDDO
 ROOT(MAX(A,B))=MIN(A,B)
ENDDO
DO I=1,N
 A=I
 DO WHILE(ROOT(A)/=A);A=ROOT(A);ENDDO
 ROOT(I)=A
ENDDO
IERR=2
DO I=1,NF
 IF (G(I)==0.OR.RIGHT(I)>0) CYCLE
 A=ROOT(LEFT(I));B=-RIGHT(I)
 IF (ANCHOR(A)>0) THEN
  IF (ABS(ANCHOR(A)-PORT_P(B))>1.E-10_EB*MAX(ANCHOR(A),PORT_P(B))) RETURN
 ENDIF
 ANCHOR(A)=PORT_P(B)
ENDDO
DO I=0,NT
 UG(I,:)=HG(I,:)-RG*REAL(I,EB)
ENDDO
TABLE(:,1:NM)=US;TABLE(:,NM+1:)=UG
STATE=0;STATE(1:NS,1:N)=GM0;STATE(NS+1,1:N)=E0
CALL RECOVER(STATE,TEMP,PRES,STAT);IERR=3
IF (STAT/=0) RETURN
TREF=MAX(1._EB,MAXVAL(TEMP))
IF (NP>0) TREF=MAX(TREF,MAXVAL(PORT_T))
SENS=MAXVAL(SUMG*MAXVAL(RG)*TREF/VP)
DTMAX=1._EB/MAX(SENS,TINY(1._EB));DT=0.05_EB*DTMAX;REJECTS=0
IERR=4
DO WHILE (.NOT.EQUILIBRIUM(PRES))
 IF (STEPS>200000.OR.REJECTS>10000) RETURN
 CALL RK4(STATE,DT,FULL,STAT)
 IF (STAT==0) CALL RK4(STATE,DT*0.5_EB,HALF,STAT)
 IF (STAT==0) CALL RK4(HALF,DT*0.5_EB,TRIAL,STAT)
 IF (STAT/=0) THEN
  DT=DT*0.5_EB;REJECTS=REJECTS+1
  IF (DT<=TINY(1._EB)) RETURN
  CYCLE
 ENDIF
 ERR=0
 DO I=1,N+NP
  DO J=1,NS+1
   SCALE=1.E-18_EB
   IF (J==NS+1) SCALE=1.E-10_EB
   SCALE=SCALE+1.E-11_EB*MAX(ABS(STATE(J,I)),ABS(TRIAL(J,I)))
   ERR=MAX(ERR,ABS(TRIAL(J,I)-FULL(J,I))/(15._EB*SCALE))
  ENDDO
 ENDDO
 IF (ERR>1) THEN
  DT=DT*MAX(0.1_EB,0.8_EB*ERR**(-0.2_EB));REJECTS=REJECTS+1;CYCLE
 ENDIF
 STATE=TRIAL;STEPS=STEPS+1
 CALL RECOVER(STATE,TEMP,PRES,STAT)
 IF (STAT/=0) RETURN
 FACTOR=2
 IF (ERR>1.E-12_EB) FACTOR=MIN(2._EB,0.9_EB*ERR**(-0.2_EB))
 DT=MIN(DTMAX,DT*FACTOR)
ENDDO
! Validate global species/energy closure, including signed exterior exchanges.
IERR=5
DO J=1,NS+1
 SCALE=MAX(1._EB,SUM(ABS(STATE(J,:))))
 IF (J<=NS) THEN
  IF (ABS(SUM(STATE(J,:))-SUM(GM0(J,:)))>1.E-10_EB*SCALE) RETURN
 ELSE
  IF (ABS(SUM(STATE(J,:))-SUM(E0))>1.E-10_EB*SCALE) RETURN
 ENDIF
ENDDO
GM1=STATE(1:NS,1:N);E1=STATE(NS+1,1:N);T1=TEMP;P1=PRES;PORT_TRANSFER=STATE(:,N+1:);IERR=0
CONTAINS
SUBROUTINE RECOVER(Y,TT,PP,STATUS)
REAL(EB),INTENT(IN) :: Y(:,:)
REAL(EB),INTENT(OUT) :: TT(:),PP(:)
INTEGER,INTENT(OUT) :: STATUS
REAL(EB) :: M(NM+NS),RES
INTEGER :: C
STATUS=1
IF (.NOT.ALL(IEEE_IS_FINITE(Y)).OR.ANY(Y(1:NS,1:N)<0)) RETURN
DO C=1,N
 M(1:NM)=SM(:,C);M(NM+1:)=Y(1:NS,C)
 IF (SUM(M)==0.AND.Y(NS+1,C)==0) THEN
  TT(C)=0;PP(C)=0;CYCLE
 ENDIF
 CALL MIXTURE_TEMPERATURE(M,TABLE,Y(NS+1,C),TT(C),RES,STATUS)
 IF (STATUS/=0) RETURN
 PP(C)=SUM(Y(1:NS,C)*RG)*TT(C)/VP(C)
 IF (.NOT.IEEE_IS_FINITE(PP(C)).OR.TT(C)<=0) THEN
  STATUS=1;RETURN
 ENDIF
ENDDO
STATUS=0
END SUBROUTINE
LOGICAL FUNCTION EQUILIBRIUM(P) RESULT(OK)
REAL(EB),INTENT(IN) :: P(:)
INTEGER :: C,J
REAL(EB) :: LO,HI,TOL
OK=.TRUE.
DO C=1,N
 IF (ROOT(C)/=C) CYCLE
 LO=MINVAL(P,MASK=ROOT==C);HI=MAXVAL(P,MASK=ROOT==C)
 TOL=1.E-12_EB+16._EB*EPSILON(1._EB)*MAX(HI,ANCHOR(C))
 IF (ANCHOR(C)>0) THEN
  IF (MAX(ABS(HI-ANCHOR(C)),ABS(LO-ANCHOR(C)))>TOL) OK=.FALSE.
 ELSE
  IF (HI-LO>TOL) OK=.FALSE.
 ENDIF
ENDDO
END FUNCTION
SUBROUTINE RHS(Y,DY,STATUS)
REAL(EB),INTENT(IN) :: Y(:,:)
REAL(EB),INTENT(OUT) :: DY(:,:)
INTEGER,INTENT(OUT) :: STATUS
REAL(EB) :: TT(N),PP(N),F,PORTPRESS,TG,Z(NS),HH,PART(NS+1),MT
INTEGER :: E,A,B,J,IT
CALL RECOVER(Y,TT,PP,STATUS)
IF (STATUS/=0) RETURN
DY=0
DO E=1,NF
 IF (G(E)==0) CYCLE
 A=LEFT(E);B=RIGHT(E)
 IF (B>0) THEN
  PORTPRESS=PP(B)
 ELSE
  PORTPRESS=PORT_P(-B)
 ENDIF
 F=G(E)*(PP(A)-PORTPRESS)
 IF (F==0) CYCLE
 IF (F>0) THEN
  MT=SUM(Y(1:NS,A));IF (MT<=0) THEN
   STATUS=1;RETURN
  ENDIF
  Z=Y(1:NS,A)/MT;TG=TT(A)
 ELSEIF (B>0) THEN
  MT=SUM(Y(1:NS,B));IF (MT<=0) THEN
   STATUS=1;RETURN
  ENDIF
  Z=Y(1:NS,B)/MT;TG=TT(B)
 ELSE
  Z=PORT_Y(:,-B);TG=PORT_T(-B)
 ENDIF
 IT=MIN(NT-1,MAX(0,INT(TG)))
 HH=SUM(Z*(HG(IT,:)+(TG-IT)*(HG(IT+1,:)-HG(IT,:))))
 PART(1:NS)=F*Z;PART(NS+1)=F*HH
 DY(:,A)=DY(:,A)-PART
 IF (B>0) THEN
  DY(:,B)=DY(:,B)+PART
 ELSE
  DY(:,N-B)=DY(:,N-B)+PART
 ENDIF
ENDDO
STATUS=0
END SUBROUTINE
SUBROUTINE RK4(Y,H,OUT,STATUS)
REAL(EB),INTENT(IN) :: Y(:,:),H
REAL(EB),INTENT(OUT) :: OUT(:,:)
INTEGER,INTENT(OUT) :: STATUS
REAL(EB) :: A(NS+1,N+NP),B(NS+1,N+NP),C(NS+1,N+NP),D(NS+1,N+NP),TMP(NS+1,N+NP),TCHK(N),PCHK(N)
CALL RHS(Y,A,STATUS);IF (STATUS/=0) RETURN
TMP=Y+0.5_EB*H*A;CALL RHS(TMP,B,STATUS);IF (STATUS/=0) RETURN
TMP=Y+0.5_EB*H*B;CALL RHS(TMP,C,STATUS);IF (STATUS/=0) RETURN
TMP=Y+H*C;CALL RHS(TMP,D,STATUS);IF (STATUS/=0) RETURN
OUT=Y+H*(A+2*B+2*C+D)/6._EB
CALL RECOVER(OUT,TCHK,PCHK,STATUS)
END SUBROUTINE
END SUBROUTINE
END MODULE
