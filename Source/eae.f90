! Global DAEM extension. Original FDS notices remain in the upstream files.
! Energy is J/mol internally here, independent of FDS's J/kmol convention.
MODULE EAE_DAEM
USE PRECISION_PARAMETERS, ONLY: EB
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
IMPLICIT NONE
PRIVATE
PUBLIC :: EAE_CONFIG,EAE_STATE,EAE_SETUP,EAE_ALLOCATE,EAE_TRIAL,EAE_ACCEPT,EAE_DIAGNOSTICS,EAE_ACTIVE,EAE_GL
INTEGER, PARAMETER, PUBLIC :: EAE_MAX_K=15,EAE_MAX_NODES=512,EAE_STATE_VERSION=1
REAL(EB), PARAMETER :: RG=8.314462618_EB
LOGICAL :: EAE_ACTIVE=.FALSE.
TYPE EAE_CONFIG
   LOGICAL :: ENABLED=.FALSE.
   INTEGER :: K=0,NN=0
   REAL(EB) :: A=0._EB,EMIN=0._EB,EMAX=0._EB
   REAL(EB), ALLOCATABLE :: ENERGY(:),WEIGHT(:)
END TYPE
TYPE EAE_STATE
   ! Mass of bins in a fixed 1 m2 planar column, kg (numerically kg/m2).
   ! REFERENCE is transported with exactly the same conservative remapping.
   REAL(EB), ALLOCATABLE :: MASS(:,:),REFERENCE(:),TRIAL(:,:)
END TYPE
CONTAINS
SUBROUTINE EAE_GL(N,LO,HI,X,W)
INTEGER, INTENT(IN) :: N
REAL(EB), INTENT(IN) :: LO,HI
REAL(EB), INTENT(OUT) :: X(N),W(N)
REAL(EB) :: Z,ZOLD,P0,P1,P2,DP
INTEGER :: I,J,ITER
DO I=1,(N+1)/2
   Z=COS(ACOS(-1._EB)*(REAL(I,EB)-0.25_EB)/(REAL(N,EB)+0.5_EB))
   DO ITER=1,100
      P0=1._EB ; P1=Z
      DO J=2,N
         P2=((2*J-1)*Z*P1-(J-1)*P0)/J ; P0=P1 ; P1=P2
      ENDDO
      IF (N==1) P0=1._EB
      DP=N*(Z*P1-P0)/(Z*Z-1._EB)
      ZOLD=Z ; Z=Z-P1/DP
      IF (ABS(Z-ZOLD)<4*EPSILON(Z)) EXIT
   ENDDO
   X(I)=(LO+HI)/2-(HI-LO)*Z/2 ; X(N+1-I)=(LO+HI)/2+(HI-LO)*Z/2
   W(I)=(HI-LO)/((1-Z*Z)*DP*DP) ; W(N+1-I)=W(I)
ENDDO
END SUBROUTINE
SUBROUTINE EAE_SETUP(C,A,K,MU,SIGMA,PI,N,NODES,EMIN,EMAX,ERROR)
TYPE(EAE_CONFIG), INTENT(OUT) :: C
REAL(EB), INTENT(IN) :: A,MU(:),SIGMA(:),PI(:),N,EMIN,EMAX
INTEGER, INTENT(IN) :: K,NODES
CHARACTER(*), INTENT(OUT) :: ERROR
REAL(EB), ALLOCATABLE :: Q(:),LOGPDF(:),LOGTERM(:)
REAL(EB) :: M,S
INTEGER :: I,J
ERROR=''
IF (.NOT.ALL(IEEE_IS_FINITE([A,N,EMIN,EMAX]))) THEN
   ERROR='EAE: nonfinite scalar'; RETURN
ENDIF
IF (K<1 .OR. K>EAE_MAX_K .OR. NODES<8 .OR. NODES>EAE_MAX_NODES) THEN
   ERROR='EAE: K must be 1..15 and NODES 8..512'; RETURN
ENDIF
IF (SIZE(MU)<K .OR. SIZE(SIGMA)<K .OR. SIZE(PI)<K) THEN
   ERROR='EAE: incomplete mixture dimensions'; RETURN
ENDIF
IF (A<=0 .OR. A>1.E100_EB .OR. N/=1 .OR. EMIN<=0 .OR. EMAX<=EMIN .OR. EMAX>10000) THEN
   ERROR='EAE: require A>0, N=1, 0<EMIN<EMAX<=10000 kJ/mol'; RETURN
ENDIF
IF (.NOT.ALL(IEEE_IS_FINITE(MU(:K))) .OR. .NOT.ALL(IEEE_IS_FINITE(SIGMA(:K))) .OR. &
    .NOT.ALL(IEEE_IS_FINITE(PI(:K)))) THEN
   ERROR='EAE: nonfinite mixture'; RETURN
ENDIF
IF (ANY(SIGMA(:K)<=0) .OR. ANY(SIGMA(:K)>10000) .OR. ANY(MU(:K)<=0) .OR. &
    ANY(MU(:K)>10000) .OR. ANY(PI(:K)<0) .OR. MAXVAL(PI(:K))<=0) THEN
   ERROR='EAE: sigma>0 and nonnegative pi with positive total required'; RETURN
ENDIF
C%A=A ; C%K=K ; C%NN=NODES ; C%EMIN=EMIN*1000 ; C%EMAX=EMAX*1000
ALLOCATE(C%ENERGY(NODES),C%WEIGHT(NODES),Q(NODES),LOGPDF(NODES),LOGTERM(K))
CALL EAE_GL(NODES,C%EMIN,C%EMAX,C%ENERGY,Q)
! Log-sum-exp prevents underflow for narrow or far-tail distributions.
DO I=1,NODES
   LOGTERM=-HUGE(1._EB)
   DO J=1,K
      IF (PI(J)<=0) CYCLE
      LOGTERM(J)=LOG(PI(J)/MAXVAL(PI(:K)))-LOG(SIGMA(J)*1000) &
         -0.5_EB*((C%ENERGY(I)-MU(J)*1000)/(SIGMA(J)*1000))**2
   ENDDO
   M=MAXVAL(LOGTERM)
   LOGPDF(I)=LOG(Q(I))+M+LOG(SUM(EXP(LOGTERM-M)))
ENDDO
IF (.NOT.ALL(IEEE_IS_FINITE(LOGPDF))) THEN
   ERROR='EAE: distribution outside numerical resolution'; RETURN
ENDIF
M=MAXVAL(LOGPDF) ; C%WEIGHT=EXP(LOGPDF-M) ; S=SUM(C%WEIGHT)
IF (.NOT.IEEE_IS_FINITE(S) .OR. S<=0) THEN
   ERROR='EAE: numerically unresolved distribution'; RETURN
ENDIF
C%WEIGHT=C%WEIGHT/S ; C%ENABLED=.TRUE.
END SUBROUTINE
SUBROUTINE EAE_ALLOCATE(S,C,NCELLS)
TYPE(EAE_STATE), INTENT(INOUT) :: S
TYPE(EAE_CONFIG), INTENT(IN) :: C
INTEGER, INTENT(IN) :: NCELLS
IF (ALLOCATED(S%MASS)) DEALLOCATE(S%MASS,S%REFERENCE,S%TRIAL)
ALLOCATE(S%MASS(C%NN,0:NCELLS+1),S%TRIAL(C%NN,0:NCELLS+1),S%REFERENCE(0:NCELLS+1))
S%MASS=0 ; S%TRIAL=0 ; S%REFERENCE=0
END SUBROUTINE
SUBROUTINE EAE_TRIAL(C,M,T,DT,LOSS,T_END)
TYPE(EAE_CONFIG), INTENT(IN) :: C
REAL(EB), INTENT(IN) :: M(:),T,DT
REAL(EB), INTENT(OUT) :: LOSS(:)
REAL(EB), INTENT(IN), OPTIONAL :: T_END
REAL(EB) :: H(SIZE(M)),X(12),W(12),TA,TB,TQ
INTEGER :: NS,IS,J
IF (PRESENT(T_END)) THEN
   NS=MAX(1,CEILING(ABS(T_END-T)/2._EB))
   CALL EAE_GL(12,-1._EB,1._EB,X,W)
   H=0
   DO IS=1,NS
      TA=T+(T_END-T)*REAL(IS-1,EB)/NS
      TB=T+(T_END-T)*REAL(IS,EB)/NS
      DO J=1,12
         TQ=(TA+TB)/2+(TB-TA)*X(J)/2
         H=H+W(J)*EXP(-C%ENERGY/(RG*MAX(TQ,1._EB)))
      ENDDO
   ENDDO
   H=MIN(700._EB,C%A*MAX(DT,0._EB)*H/(2*NS))
ELSE
   H=MIN(700._EB,C%A*EXP(-C%ENERGY/(RG*MAX(T,1._EB)))*MAX(DT,0._EB))
ENDIF
! Stable 1-exp(-h) for small h, without dependence on nonstandard EXPM1.
WHERE(H<1.E-5_EB)
   LOSS=M*H*(1-H/2+H*H/6-H**3/24)
ELSEWHERE
   LOSS=M*(1-EXP(-H))
ENDWHERE
LOSS=MAX(0._EB,MIN(M,LOSS))
END SUBROUTINE
SUBROUTINE EAE_ACCEPT(M,LOSS,ACCEPTED)
REAL(EB), INTENT(INOUT) :: M(:)
REAL(EB), INTENT(IN) :: LOSS(:),ACCEPTED
REAL(EB) :: TOTAL,F
TOTAL=SUM(LOSS)
IF (TOTAL>0) THEN
   F=MAX(0._EB,MIN(1._EB,ACCEPTED/TOTAL))
   M=MAX(0._EB,M-F*LOSS)
ELSEIF (ACCEPTED>0 .AND. SUM(M)>0) THEN
   ! Explicit FDS layer removal may consume material even with zero thermal rate.
   M=M*MAX(0._EB,1-ACCEPTED/SUM(M))
ENDIF
END SUBROUTINE
SUBROUTINE EAE_DIAGNOSTICS(C,M,REFERENCE,T,ALPHA,REMAINING,EEFF,RATE)
TYPE(EAE_CONFIG), INTENT(IN) :: C
REAL(EB), INTENT(IN) :: M(:),REFERENCE,T
REAL(EB), INTENT(OUT) :: ALPHA,REMAINING,EEFF,RATE
REAL(EB) :: LOGTERM(SIZE(M)),PIVOT,LOGRATIO
REMAINING=SUM(M) ; ALPHA=0 ; EEFF=0 ; RATE=0
IF (REFERENCE>0) ALPHA=MAX(0._EB,MIN(1._EB,1-REMAINING/REFERENCE))
IF (REMAINING<=TINY(1._EB) .OR. T<=0) RETURN
LOGTERM=-HUGE(1._EB)
WHERE(M>0) LOGTERM=LOG(MAX(M,TINY(1._EB)))-C%ENERGY/(RG*T)
PIVOT=MAXVAL(LOGTERM)
LOGRATIO=PIVOT+LOG(SUM(EXP(LOGTERM-PIVOT)))-LOG(REMAINING)
EEFF=-RG*T*LOGRATIO/1000
RATE=C%A*EXP(LOGRATIO)*REMAINING
END SUBROUTINE
END MODULE EAE_DAEM
